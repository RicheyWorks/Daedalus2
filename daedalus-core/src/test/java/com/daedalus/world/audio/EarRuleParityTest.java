package com.daedalus.world.audio;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Locale;
import org.junit.jupiter.api.Test;

/**
 * C++ = Java golden vectors for the ear rule: engines/unreal/core-test/ear_rule_parity.txt is written from the real
 * {@link CallSynth#design}, {@link CallSynth#earSafe}, {@link CallSynth#earSafePeak} and {@link CallSynth#peakHz}
 * (300 seeds x every species) and read by ear_rule_core_test.cpp against DaedalusEarRuleCore.h.
 * Regenerate with {@code -Dear.parity.write=true}. Tests only; no Java output changes.
 */
class EarRuleParityTest {
    private static final Path PARITY = Path.of("..", "engines", "unreal", "core-test", "ear_rule_parity.txt");
    private static final int SEEDS = 300;

    private static int drops(CallSpec from, CallSpec to) {
        return (int) Math.round(Math.log(from.baseHz() / to.baseHz()) / Math.log(2));
    }

    static List<String> lines() {
        List<String> out = new ArrayList<>();
        out.add("# ear_rule_parity v1: species seed genome | raw PCS 1 | raw_peak | safe_hz safe_drop | peak_hz_base peak_drop peak_hz");
        out.add("# Generated by EarRuleParityTest (Java reference). Do not edit by hand.");
        for (Species s : Species.values()) {
            for (long seed = 0; seed < SEEDS; seed++) {
                Genome g = CallSynthTest.genome(seed);
                CallSpec raw = CallSynth.design(s, g);
                CallSpec safe = CallSynth.earSafe(raw);
                CallSpec peak = CallSynth.earSafePeak(raw);
                out.add(String.format(Locale.ROOT, "%s %d %s | %s | %.6f | %.3f %d | %.3f %d %.6f", s, seed, hex(seed),
                        raw.toLine(), CallSynth.peakHz(raw), safe.baseHz(), drops(raw, safe), peak.baseHz(),
                        drops(raw, peak), CallSynth.peakHz(peak)));
            }
        }
        return out;
    }

    static String hex(long seed) {
        Rng r = new Rng(seed);
        byte[] b = new byte[12];
        for (int i = 0; i < b.length; i++) {
            b[i] = (byte) (r.nextLong() & 0xff);
        }
        return HexFormat.of().formatHex(b);
    }

    @Test
    void hexMatchesTheGenomeTheSweepsUse() {
        for (long seed = 0; seed < SEEDS; seed++) {
            assertThat(Genome.ofHex(hex(seed))).isEqualTo(CallSynthTest.genome(seed));
        }
    }

    @Test
    void parityFileIsCurrent() throws IOException {
        List<String> want = lines();
        if (Boolean.getBoolean("ear.parity.write")) {
            Files.write(PARITY, want, StandardCharsets.UTF_8);
        }
        assertThat(Files.readAllLines(PARITY, StandardCharsets.UTF_8)).containsExactlyElementsOf(want);
    }
}
