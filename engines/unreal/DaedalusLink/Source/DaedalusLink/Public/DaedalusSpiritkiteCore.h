inline const char* GameId() { return "spiritkite"; }
inline const char* Title() { return "Spiritkite Weave"; }

struct Difficulty { const char* Name; int Isles; int Wind; double Share; };
inline const Difficulty* Difficulties()
{
	static const Difficulty Table[] = {
		{ "easy", 7, 30, 0.6 },
		{ "normal", 8, 28, 0.75 },
		{ "hard", 10, 26, 0.9 } };
	return Table;
}
constexpr int DifficultyCount = 3;
inline const Difficulty* FindDifficulty(const std::string& Name)
{
	for (int I = 0; I < DifficultyCount; ++I)
	{
		if (Name == Difficulties()[I].Name) return &Difficulties()[I];
	}
	return nullptr;
}

constexpr int Inf = 1000000000;
constexpr int Anchor = 0;
constexpr int GridSpan = 10;  // isle coordinates are randint(0, 9)
constexpr int MaxLantern = 6;  // lantern values are randint(1, 6)

struct Lane { int A; int B; int Wind; };
using Matrix = std::vector<std::vector<int>>;

/** All-pairs cheapest wind (spiritkite.shortest, Floyd-Warshall in the same k/i/j order). */
inline Matrix Shortest(int N, const std::vector<Lane>& Lanes)
{
	Matrix D(static_cast<size_t>(N), std::vector<int>(static_cast<size_t>(N), Inf));
	for (int I = 0; I < N; ++I) D[static_cast<size_t>(I)][static_cast<size_t>(I)] = 0;
	for (const Lane& L : Lanes)
	{
		const int W = std::min(D[static_cast<size_t>(L.A)][static_cast<size_t>(L.B)], L.Wind);
		D[static_cast<size_t>(L.A)][static_cast<size_t>(L.B)] = W;
		D[static_cast<size_t>(L.B)][static_cast<size_t>(L.A)] = W;
	}
	for (size_t K = 0; K < D.size(); ++K)
	{
		for (size_t I = 0; I < D.size(); ++I)
		{
			for (size_t J = 0; J < D.size(); ++J)
			{
				if (D[I][K] + D[K][J] < D[I][J]) D[I][J] = D[I][K] + D[K][J];
			}
		}
	}
	return D;
}

struct Tour { int Best = 0; std::vector<int> Order; };

/** Best lantern total and visit order for a round trip from the anchor within Wind (spiritkite.best_tour). Exact. */
inline Tour BestTour(const Matrix& Dist, const std::vector<int>& Values, int Wind)
{
	const int N = static_cast<int>(Values.size());
	const int Full = 1 << N;
	Matrix Cost(static_cast<size_t>(Full), std::vector<int>(static_cast<size_t>(N), Inf));
	Matrix Prev(static_cast<size_t>(Full), std::vector<int>(static_cast<size_t>(N), -1));
	Cost[1][0] = 0;
	Tour Result;
	int BestSet = 1, BestEnd = Anchor;
	for (int S = 1; S < Full; S += 2)
	{
		for (int V = 0; V < N; ++V)
		{
			const int C = Cost[static_cast<size_t>(S)][static_cast<size_t>(V)];
			if (C >= Inf || !((S >> V) & 1)) continue;
			if (C + Dist[static_cast<size_t>(V)][Anchor] <= Wind)
			{
				int Value = 0;
				for (int I = 0; I < N; ++I) if ((S >> I) & 1) Value += Values[static_cast<size_t>(I)];
				if (Value > Result.Best) { Result.Best = Value; BestSet = S; BestEnd = V; }
			}
			for (int U = 0; U < N; ++U)
			{
				if ((S >> U) & 1) continue;
				const int Next = C + Dist[static_cast<size_t>(V)][static_cast<size_t>(U)];
				const int T = S | (1 << U);
				if (Next < Cost[static_cast<size_t>(T)][static_cast<size_t>(U)] && Next <= Wind)
				{
					Cost[static_cast<size_t>(T)][static_cast<size_t>(U)] = Next;
					Prev[static_cast<size_t>(T)][static_cast<size_t>(U)] = V;
				}
			}
		}
	}
	for (int S = BestSet, V = BestEnd; V > Anchor;)
	{
		Result.Order.push_back(V);
		const int From = Prev[static_cast<size_t>(S)][static_cast<size_t>(V)];
		S &= ~(1 << V);
		V = From;
	}
	std::reverse(Result.Order.begin(), Result.Order.end());
	return Result;
}

enum class Kind : int { Fly = 0, Land };
struct Action { Kind K = Kind::Land; int Isle = 0; };

struct Game
{
	const Difficulty* Diff = nullptr;
	std::vector<Lane> Lanes;
	std::vector<int> Values, Gathered, Trail, Plan;
	Matrix Dist, Adj;  // Adj[i][j] = lane wind, 0 when there is no lane
	int At = Anchor, Wind = 0, Target = 0;
	int Score = 0; bool Over = false, Won = false;
	pyrandom::PyRandom Rng;

	enum class Act { Ok, NotAnchor, NoLane, GameOver, FlyFirst };

	int Isles() const { return static_cast<int>(Values.size()); }

	/** PrismGame.start + Game.setup. False on an unknown difficulty. */
	bool Start(std::uint32_t Seed, const std::string& DifficultyName)
	{
		Diff = FindDifficulty(DifficultyName);
		if (!Diff) return false;
		Rng.Seed(std::string(GameId()) + ":" + std::to_string(Seed) + ":" + DifficultyName);
		Score = 0; Over = Won = false;
		const int N = Diff->Isles;
		std::vector<std::pair<int, int>> Points;
		for (int I = 0; I < N; ++I)
		{
			const int X = static_cast<int>(Rng.RandRange(GridSpan));
			const int Y = static_cast<int>(Rng.RandRange(GridSpan));
			Points.emplace_back(X, Y);
		}
		std::set<std::pair<int, int>> Pairs;
		for (int I = 1; I < N; ++I) Pairs.emplace(static_cast<int>(Rng.RandRange(static_cast<std::uint32_t>(I))), I);
		const size_t LaneCount = static_cast<size_t>(N - 1 + N / 2);
		while (Pairs.size() < LaneCount)
		{
			const std::vector<size_t> Two = Rng.SampleIndices(static_cast<size_t>(N), 2);
			const int A = static_cast<int>(std::min(Two[0], Two[1]));
			const int B = static_cast<int>(std::max(Two[0], Two[1]));
			Pairs.emplace(A, B);
		}
		Lanes.clear();
		for (const auto& P : Pairs) Lanes.push_back({ P.first, P.second, LaneWind(Points[static_cast<size_t>(P.first)], Points[static_cast<size_t>(P.second)]) });
		Values.assign(1, 0);
		for (int I = 1; I < N; ++I) Values.push_back(1 + static_cast<int>(Rng.RandRange(MaxLantern)));
		Restore();
		const Tour Best = BestTour(Dist, Values, Diff->Wind);
		Target = std::max(1, static_cast<int>(std::ceil(Best.Best * Diff->Share)));
		Plan = Best.Order;
		At = Anchor; Wind = Diff->Wind;
		Gathered.assign(1, Anchor);
		Trail.assign(1, Anchor);
		return true;
	}

	/** 1 + round(dist / 2), Python round-half-even. */
	static int LaneWind(const std::pair<int, int>& P, const std::pair<int, int>& Q)
	{
		const double Dx = P.first - Q.first, Dy = P.second - Q.second;
		return 1 + static_cast<int>(std::nearbyint(std::sqrt(Dx * Dx + Dy * Dy) / 2.0));
	}

	/** Rebuild Dist and Adj from Lanes (Game.restore). */
	void Restore()
	{
		const int N = Isles();
		Dist = Shortest(N, Lanes);
		Adj.assign(static_cast<size_t>(N), std::vector<int>(static_cast<size_t>(N), 0));
		for (const Lane& L : Lanes)
		{
			Adj[static_cast<size_t>(L.A)][static_cast<size_t>(L.B)] = L.Wind;
			Adj[static_cast<size_t>(L.B)][static_cast<size_t>(L.A)] = L.Wind;
		}
	}

	bool IsGathered(int Isle) const { return std::find(Gathered.begin(), Gathered.end(), Isle) != Gathered.end(); }

	int Lanterns() const
	{
		int Sum = 0;
		for (int I : Gathered) Sum += Values[static_cast<size_t>(I)];
		return Sum;
	}

	/** PrismGame.step + Game.act. Result gets the same text the Python act() returns. */
	Act Step(const Action& A, std::string& Result)
	{
		if (Over) return Act::GameOver;
		if (A.K == Kind::Land)
		{
			if (At != Anchor) return Act::NotAnchor;
			if (Trail.size() == 1) return Act::FlyFirst;  // spiritkite.act: "fly first" (Round 2, disk-saver 1)
			const bool Reached = Lanterns() >= Target;
			Score = Lanterns() + (Reached ? Wind : 0);
			Over = true; Won = Reached;
			Result = "landed with " + std::to_string(Lanterns());
			return Act::Ok;
		}
		if (A.Isle < 0 || A.Isle >= Isles() || Adj[static_cast<size_t>(At)][static_cast<size_t>(A.Isle)] == 0) return Act::NoLane;
		Wind -= Adj[static_cast<size_t>(At)][static_cast<size_t>(A.Isle)];
		At = A.Isle;
		Trail.push_back(At);
		int Got = 0;
		if (!IsGathered(At))
		{
			Gathered.push_back(At);
			Got = Values[static_cast<size_t>(At)];
		}
		Score = Lanterns();
		if (Dist[static_cast<size_t>(At)][Anchor] > Wind)
		{
			Over = true; Won = false;
			Result = "the kite is lost";
			return Act::Ok;
		}
		Result = "+" + std::to_string(Got);
		return Act::Ok;
	}

	/** Game.demo_action: head for the next ungathered isle on the plan (or home), cheapest lane first, lowest isle on ties. */
	Action DemoAction() const
	{
		int Goal = Anchor;
		for (int V : Plan) if (!IsGathered(V)) { Goal = V; break; }
		if (Goal == Anchor && At == Anchor) return { Kind::Land, Anchor };
		int Best = -1, BestKey = 0;
		for (int U = 0; U < Isles(); ++U)
		{
			const int W = Adj[static_cast<size_t>(At)][static_cast<size_t>(U)];
			if (W == 0) continue;
			const int Key = W + Dist[static_cast<size_t>(U)][static_cast<size_t>(Goal)];
			if (Best < 0 || Key < BestKey) { Best = U; BestKey = Key; }
		}
		return { Kind::Fly, Best };
	}
};

