// tools/minigames/spiritkite.py (prism-shard-dev), which stays the rules authority. Seeding is CPython-compatible
// (DaedalusPyRandomCore.h, "spiritkite:<seed>:<difficulty>"), so the same seed is the same sky as the Python game.
// The exact best round trip (BestTour) is the same subset DP as Python, scanned in the same order with the same strict
// comparisons, so ties resolve to the same plan. Float use and why it is safe:
//  - lane wind is 1 + round(dist / 2) on a 0..9 grid: a halfway tie needs an odd integer distance, which sqrt gives
//    exactly, so any last-bit difference between math.dist and std::sqrt cannot move the rounded result;
//    std::nearbyint uses the default round-half-even mode, matching Python's round();
//  - target is ceil(best * share): one IEEE multiply of the same doubles, identical in both languages.
// Byte parity goes through engines/unreal/core-test/spiritkite_parity.txt (spiritkite_core_test.cpp), generated by
// tools/minigames/spiritkite_parity.py.
