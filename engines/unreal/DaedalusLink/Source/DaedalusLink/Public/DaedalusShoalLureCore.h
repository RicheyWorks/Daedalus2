// Shoal Lure: header-only, engine-free C++17 port of tools/minigames/shoal_lure.py (Python is the rules authority).
// Steer a lure across a seeded current grid, net prism-fish, dodge umbra eels and dock at the Skiff; same-hue fish
// netted in a row chain (a run of k scores 1 + 2 + .. + k). All rules math is integer.
// BestTrip is the same depth-first search as Python's best_trip (ascending fish index, each prefix scored before its
// extensions, strict comparisons), so the best value, the target and the plan (tie order included) match.
// Byte parity goes through engines/unreal/core-test/shoal_lure_parity.txt (shoal_lure_core_test.cpp), generated by
// tools/minigames/shoal_lure_parity.py.
// Daedalus placement: a Prismheart cabinet on the Prism Skiff pier; source core only, no cabinet or assets yet.
