// Shardring Resonance (Prismheart cabinet, host tag PythonMinigame), plain C++17 for the Unreal binding.
// A port of tools/minigames/prism_shard.py (ShardringGame), which stays the rules authority. The Python rules draw
// shards and spirit picks from random.Random seeded by a string; that PRNG is NOT ported. Instead every random
// decision reaches this core through an Oracle supplied by the caller: the native host asks the Python rules (or a
// recorded fixture) for the next hue / spirit facet, so the two sides can never drift on arithmetic alone.
// Byte parity goes through engines/unreal/core-test/shardring_parity.txt (shardring_core_test.cpp), generated by
// tools/minigames/shardring_parity.py.
#pragma once
#include <algorithm>
#include <cstdint>
#include <set>
#include <string>
#include <vector>

namespace daedalus { namespace shardring {

inline const char* GameId() { return "shardring"; }
inline const char* Title() { return "Shardring Resonance"; }

enum class Hue : int8_t { None = -1, Ember = 0, Tide, Verdant, Gale, Umbra };
constexpr int HueCount = 5;
constexpr int Run = 3, SpiritEvery = 3, SpiritBonus = 25;

inline const char* HueName(Hue H)
{
	switch (H) { case Hue::Ember: return "ember"; case Hue::Tide: return "tide"; case Hue::Verdant: return "verdant";
	             case Hue::Gale: return "gale"; case Hue::Umbra: return "umbra"; default: return "none"; }
}
inline const char* SpiritName(Hue H)
{
	switch (H) { case Hue::Ember: return "Cinder Wisp"; case Hue::Tide: return "Mere Sprite"; case Hue::Verdant: return "Thornkin";
	             case Hue::Gale: return "Sky Lark Spirit"; case Hue::Umbra: return "Hollow Moth"; default: return ""; }
}
inline Hue HueFromName(const std::string& Name)
{
	for (int I = 0; I < HueCount; ++I) if (Name == HueName(static_cast<Hue>(I))) return static_cast<Hue>(I);
	return Hue::None;
}
inline char HueMark(Hue H) { return H == Hue::None ? '.' : static_cast<char>(HueName(H)[0] - 'a' + 'A'); }

/** Difficulty table, identical to prism_shard.DIFFICULTY. */
struct Difficulty { const char* Name; int Facets; int Hues; int Shards; };
inline const Difficulty* Difficulties()
{
	static const Difficulty Table[] = { { "easy", 14, 3, 60 }, { "normal", 10, 3, 50 }, { "hard", 8, 3, 40 } };
	return Table;
}
constexpr int DifficultyCount = 3;
inline const Difficulty* FindDifficulty(const std::string& Name)
{
	for (int I = 0; I < DifficultyCount; ++I) if (Name == Difficulties()[I].Name) return &Difficulties()[I];
	return nullptr;
}

/** Every random decision the rules make. The caller owns the source (Python rules, a fixture, or a seeded host). */
struct Oracle
{
	virtual ~Oracle() = default;
	/** The next shard hue; must be one of the first `Hues` hues of the difficulty. */
	virtual Hue Draw() = 0;
	/** A spirit's extra clear: one facet index out of `Filled` (prism_shard: rng.choice(filled)). */
	virtual int SpiritPick(const std::vector<int>& Filled) = 0;
};

/** One Shardring game: a faithful port of ShardringGame minus the PRNG. */
struct Game
{
	const Difficulty* Diff = nullptr;
	std::vector<Hue> Ring;
	int Pouch = 0, Score = 0, Chain = 0;
	int Resonance[HueCount] = { 0, 0, 0, 0, 0 };
	std::vector<Hue> Spirits;   // in summon order; SpiritName() gives the Python string
	bool Over = false, Won = false;
	Hue Current = Hue::None, Next = Hue::None;

	/** False when the difficulty is unknown. Draws the first two shards from `O` like ShardringGame.start(). */
	bool Start(const std::string& DifficultyName, Oracle& O)
	{
		Diff = FindDifficulty(DifficultyName);
		if (!Diff) return false;
		Ring.assign(static_cast<size_t>(Diff->Facets), Hue::None);
		Pouch = Diff->Shards; Score = Chain = 0;
		for (int& R : Resonance) R = 0;
		Spirits.clear(); Over = Won = false;
		Current = O.Draw(); Next = O.Draw();
		return true;
	}

	bool ValidHue(Hue H) const { return H != Hue::None && static_cast<int>(H) < Diff->Hues; }
	int Facets() const { return static_cast<int>(Ring.size()); }
	std::vector<int> EmptyFacets() const { std::vector<int> E; for (int I = 0; I < Facets(); ++I) if (Ring[static_cast<size_t>(I)] == Hue::None) E.push_back(I); return E; }
	std::vector<int> FilledFacets() const { std::vector<int> F; for (int I = 0; I < Facets(); ++I) if (Ring[static_cast<size_t>(I)] != Hue::None) F.push_back(I); return F; }

	/** The circular same-hue run through facet I (prism_shard._run_at), as a set of facet indices. */
	std::set<int> RunAt(int I) const
	{
		const int N = Facets(); const Hue H = Ring[static_cast<size_t>(I)];
		std::set<int> RunSet{ I };
		for (int Step : { 1, -1 })
		{
			int J = ((I + Step) % N + N) % N;
			while (Ring[static_cast<size_t>(J)] == H && !RunSet.count(J)) { RunSet.insert(J); J = ((J + Step) % N + N) % N; }
		}
		return RunSet;
	}

	enum class Place : int { Ok = 0, GameOver, BadFacet, BadDraw };

	/** Set the current shard in `Facet`. `Gained` receives this turn's points. Mirrors ShardringGame.place. */
	Place SetShard(int Facet, Oracle& O, int& Gained)
	{
		Gained = 0;
		if (Over) return Place::GameOver;
		if (Facet < 0 || Facet >= Facets() || Ring[static_cast<size_t>(Facet)] != Hue::None) return Place::BadFacet;
		const Hue H = Current;
		Ring[static_cast<size_t>(Facet)] = H;
		--Pouch;
		const std::set<int> RunSet = RunAt(Facet);
		if (static_cast<int>(RunSet.size()) >= Run)
		{
			++Chain;
			const int Size = static_cast<int>(RunSet.size());
			Gained = Size * Size * Chain;
			for (int J : RunSet) Ring[static_cast<size_t>(J)] = Hue::None;
			int& Res = Resonance[static_cast<int>(H)];
			++Res;
			if (Res % SpiritEvery == 0)
			{
				Spirits.push_back(H);
				Gained += SpiritBonus;
				const std::vector<int> Filled = FilledFacets();
				if (!Filled.empty())
				{
					const int Pick = O.SpiritPick(Filled);
					if (std::find(Filled.begin(), Filled.end(), Pick) == Filled.end()) return Place::BadDraw;
					Ring[static_cast<size_t>(Pick)] = Hue::None;
				}
			}
		}
		else Chain = 0;
		Score += Gained;
		Current = Next;
		Next = O.Draw();
		if (!ValidHue(Current) || !ValidHue(Next)) return Place::BadDraw;
		if (EmptyFacets().empty()) { Over = true; Won = false; }
		else if (Pouch <= 0) { Over = true; Won = true; }
		return Place::Ok;
	}

	/** prism_shard.greedy_move: prefer a resonating facet, else the biggest run, lowest index wins ties. */
	int GreedyMove() const
	{
		int Best = -1; bool BestRes = false; int BestSize = -1; int BestNegI = 0;
		Game Probe = *this;
		for (int I : EmptyFacets())
		{
			Probe.Ring[static_cast<size_t>(I)] = Current;
			const int Size = static_cast<int>(Probe.RunAt(I).size());
			Probe.Ring[static_cast<size_t>(I)] = Hue::None;
			const bool Res = Size >= Run;
			// Python key order: (size >= RUN, size, -i), greater wins
			const bool Better = Best < 0 || (Res != BestRes ? Res : (Size != BestSize ? Size > BestSize : -I > BestNegI));
			if (Better) { Best = I; BestRes = Res; BestSize = Size; BestNegI = -I; }
		}
		return Best;
	}

	/** Ring as the parity string: one mark per facet, '.' for empty. */
	std::string RingString() const { std::string S; for (Hue H : Ring) S.push_back(HueMark(H)); return S; }
};

} } // namespace daedalus::shardring
