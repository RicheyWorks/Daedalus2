inline const char* GameId() { return "glowmoss"; }
inline const char* Title() { return "Glowmoss Delve"; }

struct Difficulty { const char* Name; int Cols; int Rows; int Light; int Refill; int MossPct; int UnstablePct; int TargetPct; };
inline const Difficulty* Difficulties()
{
	static const Difficulty Table[] = {
		{ "easy", 3, 8, 12, 4, 25, 10, 75 },
		{ "normal", 4, 10, 11, 3, 18, 12, 80 },
		{ "hard", 5, 12, 10, 3, 12, 15, 86 } };
	return Table;
}
constexpr int DifficultyCount = 3;
inline const Difficulty* FindDifficulty(const std::string& Name)
{
	for (int I = 0; I < DifficultyCount; ++I)
	{
		if (Name == Difficulties()[I].Name) return &Difficulties()[I];
	}
	return nullptr;
}

constexpr int Surface = -1;
constexpr int Reach = 1;  // a dig lands at most this many columns left or right
constexpr int MaxDark = 2;
constexpr int MinGems = 1, MaxGems = 5;
constexpr int PercentScale = 100;
constexpr int PerfectBonus = 5;  // added to a winning score that gathered the best possible crystal total

using Grid = std::vector<std::vector<int>>;

/** Light needed to climb out from Row (0 from the surface). */
inline int ClimbCost(int Row) { return (Row + 2) / 2; }

inline int FirstDigCol(int Col) { return std::max(0, Col - Reach); }
inline int LastDigCol(int Col, int Cols) { return std::min(Cols - 1, Col + Reach); }

/** Light after digging onto a ledge: burn first, then the glowmoss refill, capped at the lamp. */
inline int AfterDig(int Light, const Difficulty& D, int Dark, bool Moss)
{
	Light -= 1 + Dark;
	if (Moss) Light = std::min(D.Light, Light + D.Refill);
	return Light;
}

struct Shaft { Grid Gems, Dark, Moss, Unstable; };

struct Landing { int Row; int Light; int Got; bool Mossy; bool Fell; };

/** Dig onto (Row, Col) from above (glowmoss.land): an unstable ledge drops the delver onto the ledge straight below. */
inline Landing Land(const Difficulty& D, const Shaft& S, int Row, int Col, int Light)
{
	size_t R = static_cast<size_t>(Row);
	const size_t C = static_cast<size_t>(Col);
	Landing L{ Row, AfterDig(Light, D, S.Dark[R][C], S.Moss[R][C] != 0), S.Gems[R][C], S.Moss[R][C] != 0, false };
	if (S.Unstable[R][C] != 0 && Row + 1 < D.Rows)
	{
		L.Row = Row + 1;
		L.Fell = true;
		R = static_cast<size_t>(L.Row);
		L.Got += S.Gems[R][C];
		if (S.Moss[R][C] != 0)
		{
			L.Light = std::min(D.Light, L.Light + D.Refill);
			L.Mossy = true;
		}
	}
	return L;
}

struct Delve { int Best = 0; std::vector<int> Plan; };

struct Spot { int Row; int Col; int Light; };
inline bool operator==(const Spot& A, const Spot& B) { return A.Row == B.Row && A.Col == B.Col && A.Light == B.Light; }
inline bool operator!=(const Spot& A, const Spot& B) { return !(A == B); }

/** The surface spot every delve starts from. */
inline Spot SurfaceSpot(const Difficulty& D) { return { Surface, D.Cols / 2, D.Light }; }

/** Best extra crystals and dig columns over every delve from Start that can still climb out (glowmoss.best_delve). Exact. */
inline Delve BestDelve(const Difficulty& D, const Shaft& S, const Spot& Start)
{
	struct Entry { int Crystals; Spot From; };
	using Layer = std::map<std::pair<int, int>, Entry>;  // (col, light) -> best entry
	std::vector<Layer> Layers(static_cast<size_t>(D.Rows));
	auto Expand = [&](const Spot& From, int Crystals)
	{
		for (int U = FirstDigCol(From.Col); U <= LastDigCol(From.Col, D.Cols); ++U)
		{
			const Landing L = Land(D, S, From.Row + 1, U, From.Light);
			if (L.Light < ClimbCost(L.Row)) continue;
			Layer& Target = Layers[static_cast<size_t>(L.Row)];
			const int Total = Crystals + L.Got;
			const auto Found = Target.find({ U, L.Light });
			if (Found == Target.end() || Total > Found->second.Crystals) Target[{ U, L.Light }] = { Total, From };
		}
	};
	if (Start.Row + 1 < D.Rows) Expand(Start, 0);
	Delve Result;
	Spot BestAt = Start;
	for (int R = 0; R < D.Rows; ++R)
	{
		for (const auto& [Key, E] : Layers[static_cast<size_t>(R)])
		{
			if (E.Crystals > Result.Best) { Result.Best = E.Crystals; BestAt = { R, Key.first, Key.second }; }
			if (R + 1 < D.Rows) Expand({ R, Key.first, Key.second }, E.Crystals);
		}
	}
	for (Spot At = BestAt; At != Start;)
	{
		Result.Plan.push_back(At.Col);
		At = Layers[static_cast<size_t>(At.Row)].at({ At.Col, At.Light }).From;
	}
	std::reverse(Result.Plan.begin(), Result.Plan.end());
	return Result;
}

inline Delve BestDelve(const Difficulty& D, const Shaft& S) { return BestDelve(D, S, SurfaceSpot(D)); }

constexpr const char* CodePrefix = "GLOW";

/** Shareable code for a shaft, e.g. GLOW-N-1337 (glowmoss.seed_code). */
inline std::string SeedCode(std::uint32_t Seed, const Difficulty& D)
{
	const char Initial = static_cast<char>(D.Name[0] - 'a' + 'A');
	return std::string(CodePrefix) + "-" + Initial + "-" + std::to_string(Seed);
}

/** Seed and difficulty from a seed code (glowmoss.parse_seed_code: trimmed, case-insensitive). False when it is not
 *  one. Native seeds are uint32, so codes with more than 9 seed digits are refused here. */
inline bool ParseSeedCode(const std::string& Code, std::uint32_t& Seed, const Difficulty*& D)
{
	const char* Space = " \t\r\n";
	const size_t First = Code.find_first_not_of(Space);
	if (First == std::string::npos) return false;
	std::string Upper = Code.substr(First, Code.find_last_not_of(Space) - First + 1);
	for (char& Ch : Upper) if (Ch >= 'a' && Ch <= 'z') Ch = static_cast<char>(Ch - 'a' + 'A');
	const std::string Prefix = std::string(CodePrefix) + "-";
	if (Upper.rfind(Prefix, 0) != 0 || Upper.size() < Prefix.size() + 3 || Upper[Prefix.size() + 1] != '-') return false;
	D = nullptr;
	for (int I = 0; I < DifficultyCount; ++I)
	{
		if (Difficulties()[I].Name[0] - 'a' + 'A' == Upper[Prefix.size()]) D = &Difficulties()[I];
	}
	const std::string Digits = Upper.substr(Prefix.size() + 2);
	if (!D || Digits.empty() || Digits.size() > 9) return false;
	for (char Ch : Digits) if (Ch < '0' || Ch > '9') return false;
	Seed = static_cast<std::uint32_t>(std::stoul(Digits));
	return true;
}

/** Everyone delves the same shaft on the same day: the date as YYYYMMDD (glowmoss.daily_seed). */
inline std::uint32_t DailySeed(int Year, int Month, int Day) { return static_cast<std::uint32_t>(Year * 10000 + Month * 100 + Day); }

enum class Kind : int { Dig = 0, Climb };
struct Action { Kind K = Kind::Climb; int Col = 0; };

struct Game
{
	const Difficulty* Diff = nullptr;
	Shaft Cells;
	std::vector<int> Plan, Path;
	int Row = Surface, Col = 0, Light = 0, Crystals = 0, Best = 0, Target = 0;
	int Score = 0; bool Over = false, Won = false, Perfect = false;
	pyrandom::PyRandom Rng;

	enum class Act { Ok, Floor, OutOfReach, GameOver };

	/** PrismGame.start + Game.setup. False on an unknown difficulty. */
	bool Start(std::uint32_t Seed, const std::string& DifficultyName)
	{
		Diff = FindDifficulty(DifficultyName);
		if (!Diff) return false;
		Rng.Seed(std::string(GameId()) + ":" + std::to_string(Seed) + ":" + DifficultyName);
		Score = 0; Over = Won = false;
		const size_t Rows = static_cast<size_t>(Diff->Rows), Cols = static_cast<size_t>(Diff->Cols);
		Cells.Gems.assign(Rows, std::vector<int>(Cols, 0));
		Cells.Dark = Cells.Gems;
		Cells.Moss = Cells.Gems;
		Cells.Unstable = Cells.Gems;
		for (size_t R = 0; R < Rows; ++R)
		{
			for (size_t C = 0; C < Cols; ++C)
			{
				Cells.Gems[R][C] = MinGems + static_cast<int>(Rng.RandRange(MaxGems - MinGems + 1));
				Cells.Dark[R][C] = static_cast<int>(Rng.RandRange(MaxDark + 1));
				Cells.Moss[R][C] = static_cast<int>(Rng.RandRange(PercentScale)) < Diff->MossPct ? 1 : 0;
				Cells.Unstable[R][C] = static_cast<int>(Rng.RandRange(PercentScale)) < Diff->UnstablePct ? 1 : 0;
			}
		}
		const Delve Delved = BestDelve(*Diff, Cells);
		Plan = Delved.Plan;
		Best = Delved.Best;
		Target = std::max(1, Best * Diff->TargetPct / PercentScale);
		Perfect = false;
		Row = Surface; Col = Diff->Cols / 2; Light = Diff->Light; Crystals = 0;
		Path.clear();
		return true;
	}

	/** PrismGame.step + Game.act. Result gets the same text the Python act() returns. */
	Act Step(const Action& A, std::string& Result)
	{
		if (Over) return Act::GameOver;
		if (A.K == Kind::Climb)
		{
			const bool Reached = Crystals >= Target;
			Light -= ClimbCost(Row);
			Perfect = Reached && Crystals == Best;
			Score = Crystals + (Reached ? Light : 0) + (Perfect ? PerfectBonus : 0);
			Over = true; Won = Reached;
			Result = "climbed out with " + std::to_string(Crystals) + (Perfect ? " (perfect delve)" : "");
			return Act::Ok;
		}
		if (Row + 1 >= Diff->Rows) return Act::Floor;
		if (A.Col < FirstDigCol(Col) || A.Col > LastDigCol(Col, Diff->Cols)) return Act::OutOfReach;
		const Landing L = Land(*Diff, Cells, Row + 1, A.Col, Light);
		Row = L.Row;
		Light = L.Light;
		Col = A.Col;
		Path.push_back(Col);
		Crystals += L.Got;
		Score = Crystals;
		if (Light < ClimbCost(Row))
		{
			Over = true; Won = false;
			Result = "the lamp gutters out";
			return Act::Ok;
		}
		Result = "+" + std::to_string(L.Got) + (L.Mossy ? " glowmoss" : "") + (L.Fell ? " crumble" : "");
		return Act::Ok;
	}

	/** Game.hint: the first dig of the best delve from the current ledge, else climb out. */
	Action Hint() const
	{
		const Delve FromHere = BestDelve(*Diff, Cells, { Row, Col, Light });
		if (FromHere.Plan.empty()) return { Kind::Climb, 0 };
		return { Kind::Dig, FromHere.Plan.front() };
	}

	/** Game.demo_action: dig the best plan, then climb out. */
	Action DemoAction() const
	{
		if (Path.size() < Plan.size()) return { Kind::Dig, Plan[Path.size()] };
		return { Kind::Climb, 0 };
	}
};

