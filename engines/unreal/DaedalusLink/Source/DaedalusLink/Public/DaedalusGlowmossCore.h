// (prism-shard-dev), which stays the rules authority. Seeding is CPython-compatible (DaedalusPyRandomCore.h,
// "glowmoss:<seed>:<difficulty>"), so the same seed is the same shaft as the Python game. All rules math is integer.
// BestDelve is the same exact DP over (row, col, light) as Python's best_delve, expanded in the same row and sorted
