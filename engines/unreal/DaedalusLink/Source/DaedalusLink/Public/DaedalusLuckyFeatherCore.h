#pragma once
#include <cmath>
#include <cstdint>
#include <vector>

namespace daedalus { namespace luckyfeather {

inline const char* GameId() { return "luckyfeather"; }
inline const char* Title() { return "Lucky Feather"; }
constexpr int AviaryCap = 20;   // G163 studbook aviary cap

struct Settings
{
	int Flock = AviaryCap;      // N
	double Fitness = 1.0;       // r
	int Start = 1;              // i
	int MaxSteps = 1000000;

	// Same rules as the Java record's compact constructor.
	bool Valid() const
	{
		return Flock >= 2 && Flock <= 10000 && Fitness > 0 && !std::isinf(Fitness) && Start >= 0 && Start <= Flock
			&& MaxSteps >= 1;
	}
};

struct Result { double Fixed = 0; double MeanSteps = 0; int Capped = 0; int FixedRuns = 0; };

namespace detail {
inline uint64_t Mix(uint64_t Z)
{
	Z = (Z ^ (Z >> 30)) * 0xBF58476D1CE4E5B9ull;
	Z = (Z ^ (Z >> 27)) * 0x94D049BB133111EBull;
	return Z ^ (Z >> 31);
}
// Java: mix(seed ^ C); mix(h ^ run) with the int run sign-extended; mix(h ^ step).
inline double Uniform(int64_t Seed, int Run, int64_t Step)
{
	uint64_t H = Mix(static_cast<uint64_t>(Seed) ^ 0xA54FF53A5F1D36F1ull);
	H = Mix(H ^ static_cast<uint64_t>(static_cast<int64_t>(Run)));
	H = Mix(H ^ static_cast<uint64_t>(Step));
	return static_cast<double>(H >> 11) * 0x1.0p-53;
}
inline std::vector<double> Thomas(const std::vector<double>& A, const std::vector<double>& B,
	const std::vector<double>& C, const std::vector<double>& D)
{
	const size_t N = B.size();
	std::vector<double> Cp(N), Dp(N), X(N);
	Cp[0] = C[0] / B[0];
	Dp[0] = D[0] / B[0];
	for (size_t I = 1; I < N; ++I)
	{
		const double M = B[I] - A[I] * Cp[I - 1];
		Cp[I] = C[I] / M;
		Dp[I] = (D[I] - A[I] * Dp[I - 1]) / M;
	}
	X[N - 1] = Dp[N - 1];
	for (size_t I = N - 1; I-- > 0;) X[I] = Dp[I] - Cp[I] * X[I + 1];
	return X;
}
} // namespace detail

class Aviary
{
public:
	explicit Aviary(const Settings& In) : S(In) {}
	const Settings& GetSettings() const { return S; }

	// Same expression order as Java so the doubles match bit for bit.
	double Up(int I) const
	{
		const int N = S.Flock; const double R = S.Fitness;
		return R * I / (R * I + N - I) * (N - I) / N;
	}
	double Down(int I) const
	{
		const int N = S.Flock; const double R = S.Fitness;
		return (N - I) / (R * I + N - I) * I / N;
	}

	// Closed form (1 - r^-i) / (1 - r^-N); i / N when r = 1. Returns -1 for i out of range.
	double Fixation(int I) const
	{
		const int N = S.Flock;
		if (I < 0 || I > N) return -1;
		const double R = S.Fitness;
		if (std::fabs(R - 1) < 1e-12) return static_cast<double>(I) / N;
		const double Lr = std::log(R);
		return std::expm1(-I * Lr) / std::expm1(-N * Lr);
	}
	double Fixation() const { return Fixation(S.Start); }

	std::vector<double> Exact() const { return Solve(false); }
	std::vector<double> MeanStepsAll() const { return Solve(true); }
	double MeanSteps() const { return MeanStepsAll()[static_cast<size_t>(S.Start)]; }

	// Fewest starting carriers whose fixation chance reaches Target; -1 for a bad target.
	int CarriersNeeded(double Target) const
	{
		if (!(Target >= 0) || Target > 1) return -1;
		for (int I = 0; I <= S.Flock; ++I) if (Fixation(I) >= Target - 1e-12) return I;
		return S.Flock;
	}

	Result Simulate(int Runs, int64_t Seed) const
	{
		Result Out;
		if (Runs < 1) return Out;
		const int N = S.Flock;
		double Steps = 0;
		for (int Run = 0; Run < Runs; ++Run)
		{
			int I = S.Start;
			int64_t K = 0;
			while (I > 0 && I < N && K < S.MaxSteps)
			{
				const double U = detail::Uniform(Seed, Run, K);
				const double Pu = Up(I);
				if (U < Pu) ++I;
				else if (U < Pu + Down(I)) --I;
				++K;
			}
			if (I == N) ++Out.FixedRuns;
			else if (I > 0) ++Out.Capped;
			Steps += static_cast<double>(K);
		}
		Out.Fixed = static_cast<double>(Out.FixedRuns) / Runs;
		Out.MeanSteps = Steps / Runs;
		return Out;
	}

private:
	Settings S;

	std::vector<double> Solve(bool Steps) const
	{
		const size_t N = static_cast<size_t>(S.Flock);
		std::vector<double> Lo(N + 1, 0.0), Di(N + 1, 0.0), Hi(N + 1, 0.0), Rhs(N + 1, 0.0);
		Di[0] = 1;
		Di[N] = 1;
		if (!Steps) Rhs[N] = 1;
		for (size_t I = 1; I < N; ++I)
		{
			const int Ii = static_cast<int>(I);
			Lo[I] = -Down(Ii);
			Di[I] = Up(Ii) + Down(Ii);
			Hi[I] = -Up(Ii);
			if (Steps) Rhs[I] = 1;
		}
		return detail::Thomas(Lo, Di, Hi, Rhs);
	}
};

}} // namespace daedalus::luckyfeather
