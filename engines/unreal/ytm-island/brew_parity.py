"""Parity fixture for the Java Melody Brewing core (daedalus-core com.daedalus.world.brew, contest G25).

Runs herbcombo.brew() over every ordered 3-herb kettle (12x11x10 = 1320, stage 2), 600 seeded 3-5 herb kettles with
mixed stages (repeats and cadences included), wrong counts, and every found tune; writes a TSV MelodyBrewParityTest
replays, and copies found_tunes.csv next to it so the Java tests read the real tune list.

    python engines/unreal/ytm-island/brew_parity.py          # rewrite
    python engines/unreal/ytm-island/brew_parity.py --check  # exit 1 if stale (test_brew_parity.py)

Line: herbs(a|b|c) stages(2|3|1) -> tonic melody effect purifies tier magnitude duration notes steps
"""
import itertools
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, HERE)
import herbcombo as H  # noqa: E402

RES = os.path.join(ROOT, "daedalus-core", "src", "test", "resources", "com", "daedalus", "world", "brew")
OUT = os.path.join(RES, "melody-parity.tsv")
TUNES_SRC = os.path.join(HERE, "found_tunes.csv")
TUNES_OUT = os.path.join(RES, "found_tunes.csv")


def j(xs, sep="|"):
    xs = list(xs)
    return sep.join(str(x) for x in xs) if xs else "-"


def row(herbs, stages):
    r = H.brew(list(zip(herbs, stages)))
    return "\t".join([j(herbs), j(stages), r["tonic"], r["melody"], r["effect"], str(int(bool(r.get("purifies_water", False)))),
                      str(r["tier"]), str(r.get("magnitude", 0)), str(r.get("duration_s", 0)), j(r.get("notes", [])), j(r.get("steps", []))])


def render():
    names = list(H.HERBS)
    rows = ["# generated by engines/unreal/ytm-island/brew_parity.py from herbcombo.py; do not edit"]
    for combo in itertools.permutations(names, 3):
        rows.append(row(combo, (2, 2, 2)))
    rng = random.Random(20261019)
    for _ in range(600):
        n = rng.choice((3, 4, 5))
        herbs = [rng.choice(names) for _ in range(n)]
        if rng.random() < 0.3:
            herbs[-1] = herbs[0]                      # make cadences common
        rows.append(row(herbs, [rng.randint(1, 4) for _ in herbs]))
    for herbs in (names[:2], names[:6], names[:1]):
        rows.append(row(herbs, [2] * len(herbs)))     # wrong counts -> Noise
    with open(TUNES_SRC, encoding="utf-8") as f:
        for line in f.read().splitlines()[1:]:
            herbs = line.split(",")[2].split("|")
            rows.append(row(herbs, [3] * len(herbs)))
    return "\n".join(rows) + "\n"


def main(argv):
    text = render()
    with open(TUNES_SRC, encoding="utf-8") as f:
        tunes = f.read()
    if "--check" in argv:
        ok = all(os.path.exists(p) for p in (OUT, TUNES_OUT))
        ok = ok and open(OUT, encoding="utf-8").read() == text and open(TUNES_OUT, encoding="utf-8").read() == tunes
        print("fixture %s" % ("up to date" if ok else "STALE: run python engines/unreal/ytm-island/brew_parity.py"))
        return 0 if ok else 1
    os.makedirs(RES, exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    with open(TUNES_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(tunes)
    print("wrote %s (%d rows) + found_tunes.csv" % (OUT, text.count("\n") - 1))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
