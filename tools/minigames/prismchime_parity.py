#!/usr/bin/env python3
"""Prismchime Ring parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/prismchime_parity.txt from tools/minigames/prismchime.py for a fixed set of
seeds x difficulties, playing demo_action to the end:

  game s=<seed> d=<difficulty> taps=<t> charge=<c,c,...> facing=<+1,-1,...>
  move t=<turn> tap=<i> pealed=<n> score=<s> taps=<t> lit=<0/1...> charge=<c,...> over=<0|1> won=<0|1> res=<text>
  end  score=<s> won=<0|1> peals=<n>

DaedalusPrismchimeCore.h seeds its own CPython-compatible stream from "prismchime:<seed>:<difficulty>", so the
generated ring itself is the parity check. Run with --check to verify the committed file is current.
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import prismchime as pm  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "prismchime_parity.txt")


def ints(v):
    return ",".join(str(x) for x in v)


def play(seed, difficulty):
    g = pm.Game(seed, difficulty)
    lines = ["game s=%d d=%s taps=%d charge=%s facing=%s" % (seed, difficulty, g.taps, ints(g.charge),
                                                           ",".join("%+d" % f for f in g.facing))]
    turn = 0
    while not g.over:
        i = g.demo_action()
        res = g.step(i)
        pealed = int(re.search(r"(\d+) peal", res).group(1))
        turn += 1
        lines.append("move t=%d tap=%d pealed=%d score=%d taps=%d lit=%s charge=%s over=%d won=%d res=%s"
                     % (turn, i, pealed, g.score, g.taps, "".join("1" if x else "0" for x in g.lit), ints(g.charge),
                        int(g.over), int(g.won), res))
    lines.append("end  score=%d won=%d peals=%d" % (g.score, int(g.won), g.peals))
    return lines


def generate():
    out = ["# prismchime_parity.txt: generated by tools/minigames/prismchime_parity.py from prismchime.py (Python rules "
           "are the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
