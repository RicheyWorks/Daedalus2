#!/usr/bin/env python3
"""Shardscale parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/shardscale_parity.txt from tools/minigames/shardscale.py for a fixed set of
seeds x difficulties, playing demo_action (the exact weigher) to the end:

  game s=<seed> d=<difficulty> shards=<n> cap=<c> tol=<t> bench=<b> line=<w,w,...>
  move t=<turn> act=<l|r|hold|l<n>|r<n>> index=<i> left=<L> right=<R> held=<w,...|-> used=<k> score=<s> over=<0|1> won=<0|1> res=<text>
  end  score=<s> won=<0|1> left=<L> right=<R>

Edge-case vectors follow the seeded lines: a hand-set line and state (no seed) and one scripted action each, so both
sides prove the rule corners (a tip, the last shard levelling, askew, a bench shard set, a full bench) and the
weigher's pick on states the seeds may never produce:

  vector <name> shards=<n> cap=<c> tol=<t> bench=<b> line=<...> index=<i> left=<L> right=<R> held=<...|-> used=<k>
  step act=<...> demo=<...> index=<i> left=<L> right=<R> held=<...> used=<k> score=<s> over=<0|1> won=<0|1> res=<text>

DaedalusShardscaleCore.h seeds its own CPython-compatible stream from "shardscale:<seed>:<difficulty>" and repeats
the redraw-until-solvable loop, so the generated line itself is the parity check, and the weigher's exact search
(actions in the rules' order, first winning action) must match turn for turn. Run with --check to verify the
committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import shardscale as ss  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "shardscale_parity.txt")


def act_text(action):
    kind, source = action
    if kind == "hold":
        return "hold"
    return kind[0] + ("" if source == "next" else str(source))


def ints(v):
    return ",".join(str(x) for x in v) or "-"


def play(seed, difficulty):
    g = ss.Game(seed, difficulty)
    cfg = g.cfg
    lines = ["game s=%d d=%s shards=%d cap=%d tol=%d bench=%d line=%s"
             % (seed, difficulty, cfg["shards"], cfg["cap"], cfg["tolerance"], cfg["bench"], ints(g.line))]
    turn = 0
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        turn += 1
        lines.append("move t=%d act=%s index=%d left=%d right=%d held=%s used=%d score=%d over=%d won=%d res=%s"
                     % (turn, act_text(a), g.index, g.left, g.right, ints(g.held), g.bench_used, g.score, int(g.over),
                        int(g.won), res))
    lines.append("end  score=%d won=%d left=%d right=%d" % (g.score, int(g.won), g.left, g.right))
    return lines


VECTORS = (
    # name, line, cap, tol, bench, index, left, right, held, used, action
    ("tip_on_the_first_shard", [9, 1], 5, 1, 2, 0, 0, 0, [], 0, ("left", "next")),
    ("last_shard_levels", [4, 4], 5, 1, 2, 1, 4, 0, [], 0, ("right", "next")),
    ("last_shard_askew", [4, 1], 5, 1, 2, 1, 4, 0, [], 0, ("right", "next")),
    ("bench_shard_set_right", [3, 4, 2], 5, 1, 2, 3, 3, 2, [4], 1, ("right", 0)),
    ("hold_sorts_the_bench", [3, 7, 5], 5, 1, 3, 1, 0, 0, [7], 1, ("hold", "next")),
    ("weigher_benches_a_heavy_shard", [9, 4, 5], 5, 1, 2, 0, 0, 0, [], 0, ("hold", "next")),
    ("weigher_sets_the_lighter_pan", [2, 2], 5, 0, 2, 1, 2, 0, [], 0, ("right", "next")),
    ("weigher_clears_the_bench_last", [6, 1, 5], 5, 0, 2, 3, 1, 0, [6, 5], 2, ("left", 0)),
    ("score_counts_slack_and_bench", [4, 4], 6, 2, 3, 1, 4, 0, [], 0, ("right", "next")),
)


def vector(name, line, cap, tol, bench, index, left, right, held, used, action):
    g = ss.Game(1, "easy")
    g.cfg = dict(g.cfg, shards=len(line), cap=cap, tolerance=tol, bench=bench)
    g.line, g.index, g.left, g.right, g.held, g.bench_used, g.tipped = list(line), index, left, right, sorted(held), used, False
    lines = ["vector %s shards=%d cap=%d tol=%d bench=%d line=%s index=%d left=%d right=%d held=%s used=%d"
             % (name, len(line), cap, tol, bench, ints(line), index, left, right, ints(g.held), used)]
    demo = g.demo_action()
    res = g.step(action)
    lines.append("step act=%s demo=%s index=%d left=%d right=%d held=%s used=%d score=%d over=%d won=%d res=%s"
                 % (act_text(action), act_text(demo), g.index, g.left, g.right, ints(g.held), g.bench_used, g.score,
                    int(g.over), int(g.won), res))
    return lines


def generate():
    out = ["# shardscale_parity.txt: generated by tools/minigames/shardscale_parity.py from shardscale.py (Python rules "
           "are the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    for v in VECTORS:
        out += vector(*v)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
