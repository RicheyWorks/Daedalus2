#!/usr/bin/env python3
"""Fogbell Ferry parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/fogbell_parity.txt from tools/minigames/fogbell.py for a fixed set of
seeds x difficulties, playing demo_action to the end:

  game s=<seed> d=<difficulty> size=<n> heights=<row|row|...> ferry=<r,c> harbour=<r,c> passengers=<r,c;...>
  move t=<turn> act=<n|e|s|w|wait> ferry=<r,c> tide=<t> aboard=<a> passengers=<r,c;...|-> score=<s> over=<0|1> won=<0|1> res=<text>
  end  score=<s> won=<0|1> aboard=<a> turns=<t>

Edge-case vectors follow the seeded voyages: a hand-set flat (no seed), a turn, and one scripted move each, so both
sides prove the BFS routing, the tide edge and the harbour rules on states the seeds may never produce:

  vector <name> size=<n> heights=<row|...> ferry=<r,c> turn=<t> aboard=<a> need=<k> passengers=<r,c;...|->
  step act=<move> demo=<move> ferry=<r,c> tide=<t> aboard=<a> passengers=<...> score=<s> over=<0|1> won=<0|1> res=<text>

DaedalusFogbellCore.h seeds its own CPython-compatible stream from "fogbell:<seed>:<difficulty>", so the generated
flat itself is the parity check, and the demo path (flood-aware BFS in n/e/s/w order) must match step for step.
Run with --check to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fogbell as fb  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "fogbell_parity.txt")


def cells(v):
    return ";".join("%d,%d" % (r, c) for r, c in v) or "-"


def play(seed, difficulty):
    g = fb.Game(seed, difficulty)
    lines = ["game s=%d d=%s size=%d heights=%s ferry=%d,%d harbour=%d,%d passengers=%s"
             % (seed, difficulty, g.size(), "|".join("".join(str(h) for h in row) for row in g.heights),
                g.ferry[0], g.ferry[1], g.harbour[0], g.harbour[1], cells(g.passengers))]
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        lines.append("move t=%d act=%s ferry=%d,%d tide=%d aboard=%d passengers=%s score=%d over=%d won=%d res=%s"
                     % (g.turn, a, g.ferry[0], g.ferry[1], g.tide, g.aboard, cells(g.passengers), g.score,
                        int(g.over), int(g.won), res))
    lines.append("end  score=%d won=%d aboard=%d turns=%d" % (g.score, int(g.won), g.aboard, g.turn))
    return lines


VECTORS = (
    # name, rows, ferry, turn, aboard, need, passengers, scripted move
    ("route_around_flooding_cell", ["3133", "3333", "3333", "3333"], (0, 0), 2, 0, 1, [(0, 3)], "s"),
    ("wait_on_dry_ground", ["3333", "3333", "3333", "3333"], (1, 1), 2, 0, 1, [], "wait"),
    ("tide_takes_the_ferry", ["313", "333", "333"], (0, 1), 2, 0, 1, [], "wait"),
    ("harbour_with_enough", ["33", "33"], (0, 1), 1, 1, 1, [], "s"),
    ("harbour_too_few", ["33", "33"], (1, 0), 1, 0, 1, [(0, 1)], "e"),
    ("pick_up_on_the_way", ["333", "333", "333"], (0, 0), 0, 0, 2, [(0, 1), (2, 2)], "e"),
    ("stranded_waits", ["31", "13"], (0, 0), 3, 0, 1, [], "wait"),
    ("enough_aboard_heads_home", ["3333", "3333", "3333", "3333"], (1, 1), 0, 1, 1, [(0, 3)], "e"),
)


def vector(name, rows, ferry, turn, aboard, need, passengers, move):
    g = fb.Game(1, "easy")
    s = len(rows)
    g.cfg = dict(g.cfg, size=s, passengers=len(passengers) + aboard, need=need)
    g.heights = [[int(ch) for ch in row] for row in rows]
    g.ferry, g.harbour = list(ferry), [s - 1, s - 1]
    g.passengers = [list(p) for p in passengers]
    g.aboard, g.turn = aboard, turn
    lines = ["vector %s size=%d heights=%s ferry=%d,%d turn=%d aboard=%d need=%d passengers=%s"
             % (name, s, "|".join(rows), ferry[0], ferry[1], turn, aboard, need, cells(g.passengers))]
    demo = g.demo_action()
    res = g.step(move)
    lines.append("step act=%s demo=%s ferry=%d,%d tide=%d aboard=%d passengers=%s score=%d over=%d won=%d res=%s"
                 % (move, demo, g.ferry[0], g.ferry[1], g.tide, g.aboard, cells(g.passengers), g.score, int(g.over),
                    int(g.won), res))
    return lines


def generate():
    out = ["# fogbell_parity.txt: generated by tools/minigames/fogbell_parity.py from fogbell.py (Python rules are the "
           "authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    for v in VECTORS:
        out += vector(*v)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
