#!/usr/bin/env python3
"""Glimmerloom Ledger parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/glimmerloom_parity.txt from tools/minigames/glimmerloom.py for a fixed set of
seeds x difficulties, playing demo_action to the end:

  game s=<seed> d=<difficulty> day=<d> purse=<p> score=<s> prices=<..> satchel=<..> moves=<..> rumor=<hue>:<rise|fall>
  move t=<turn> act=<buy:i:n|sell:i:n|rest> day=.. purse=.. score=.. prices=.. satchel=.. moves=.. rumor=.. over=<0|1> won=<0|1> res=<text>
  end  score=<s> won=<0|1>

No RNG events are recorded: DaedalusGlimmerloomCore.h seeds its own CPython-compatible stream from
"glimmerloom:<seed>:<difficulty>", so the opening prices, every rolled price move and every rumor are part of the
parity check. All market math is integer; the only float is random() compared with the rumor truth rate, and
random() is bit-exact in DaedalusPyRandomCore.h.
Run `python tools/minigames/glimmerloom_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import glimmerloom as gl  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "glimmerloom_parity.txt")


def ints(xs):
    return ",".join(str(x) for x in xs)


def act_str(a):
    return a[0] if a[0] == "rest" else "%s:%d:%d" % a


def state_str(g):
    return "day=%d purse=%d score=%d prices=%s satchel=%s moves=%s rumor=%d:%s" % (
        g.day, g.purse, g.score, ints(g.prices), ints(g.satchel), ints(g.moves), g.rumor[0], g.rumor[1])


def play(seed, difficulty):
    g = gl.Game(seed, difficulty)
    lines = ["game s=%d d=%s %s" % (seed, difficulty, state_str(g))]
    turn = 0
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        turn += 1
        lines.append("move t=%d act=%s %s over=%d won=%d res=%s" % (turn, act_str(a), state_str(g), int(g.over), int(g.won), res))
    lines.append("end  score=%d won=%d" % (g.score, int(g.won)))
    return lines


def generate():
    out = ["# glimmerloom_parity.txt: generated by tools/minigames/glimmerloom_parity.py from glimmerloom.py (Python rules "
           "are the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
