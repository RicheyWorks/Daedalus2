#!/usr/bin/env python3
"""Shoal Lure parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/shoal_lure_parity.txt from tools/minigames/shoal_lure.py for a fixed set of
seeds x difficulties, playing demo_action to the end:

  game s=<seed> d=<difficulty> current=<row/row..> fish=<cell:hue,..> eels=<..> best=<b> target=<t> plan=<..> <state>
  probe k=<stamina> best=<value> order=<..>   (biggest shoal from the Skiff with only k stamina)
  move t=<turn> act=<n|e|s|w|net|dock> <state> hint=<..> over=<0|1> won=<0|1> res=<text with _ for spaces>
  end  score=<s> won=<0|1>

  <state> = at=<cell> stamina=<k> score=<s> netted=<..> shoal=<..> moves=<m>

DaedalusShoalLureCore.h seeds its own CPython-compatible stream from "shoal_lure:<seed>:<difficulty>", so the current
grid, the fish and eels, the exact best trip (target and plan), every demo move and the hint after it are all checked.
Run `python tools/minigames/shoal_lure_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import shoal_lure as sl  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
PROBES = (6, 10, 14)
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "shoal_lure_parity.txt")


def ints(xs):
    return ",".join(str(x) for x in xs)


def act_str(a):
    return "nesw"[a[1]] if a[0] == "move" else a[0]


def state_str(g):
    return "at=%d stamina=%d score=%d netted=%s shoal=%s moves=%d" % (
        g.at, g.stamina, g.score, ints(g.netted), ints(g.shoal), g.moves)


def play(seed, difficulty):
    g = sl.Game(seed, difficulty)
    cur = "/".join("".join(str(x) for x in row) for row in g.current)
    fish = ",".join("%d:%d" % (c, h) for c, h in g.fish)
    lines = ["game s=%d d=%s current=%s fish=%s eels=%s best=%d target=%d plan=%s %s" % (
        seed, difficulty, cur, fish, ints(g.eels), g.best, g.target, ints(g.plan), state_str(g))]
    for k in PROBES:
        best, order = sl.best_trip(g.dist, g.fish, g.home(), g.home(), k, [])
        lines.append("probe k=%d best=%d order=%s" % (k, best, ints(order)))
    turn = 0
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        turn += 1
        hint = act_str(g.hint()) if not g.over else "-"
        lines.append("move t=%d act=%s %s hint=%s over=%d won=%d res=%s" % (
            turn, act_str(a), state_str(g), hint, g.over, g.won, res.replace(" ", "_")))
    lines.append("end  score=%d won=%d" % (g.score, g.won))
    return lines


def build():
    out = ["# shoal_lure parity v1 (generated by tools/minigames/shoal_lure_parity.py; do not edit)"]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("shoal_lure_parity.txt is stale: run python tools/minigames/shoal_lure_parity.py")
                return 1
        print("parity file current")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.normpath(OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
