#!/usr/bin/env python3
"""Shardfall Gamble parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/shardfall_parity.txt from tools/minigames/shardfall.py:

  game s=<seed> d=<difficulty> round=<r> bag=<v,v,...>
  move t=<turn> act=<draw|bank> res=<+v|cracked|collapse|banked_n> round=<r> pot=<p> cracks=<c> score=<s> bag=<...|-> history=<...|-> over=<0|1> won=<0|1>
  end  score=<s> won=<0|1> rounds=<r>

Run `python tools/minigames/shardfall_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import shardfall as sf  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "shardfall_parity.txt")


def lst(v):
    return ",".join(map(str, v)) if v else "-"


def play(seed, difficulty):
    g = sf.Game(seed, difficulty)
    lines = ["game s=%d d=%s round=%d bag=%s" % (seed, difficulty, g.round, lst(g.bag))]
    turn = 0
    while not g.over:
        a = g.demo_action()
        r = g.step(a).replace(" ", "_")
        turn += 1
        lines.append("move t=%d act=%s res=%s round=%d pot=%d cracks=%d score=%d bag=%s history=%s over=%d won=%d"
                     % (turn, a, r, g.round, g.pot, g.cracks, g.score, lst(g.bag), lst(g.history), int(g.over), int(g.won)))
    lines.append("end  score=%d won=%d rounds=%d" % (g.score, int(g.won), g.round))
    return lines


def generate():
    out = ["# shardfall_parity.txt: generated by tools/minigames/shardfall_parity.py from shardfall.py (Python rules are "
           "the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
