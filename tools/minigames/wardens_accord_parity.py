#!/usr/bin/env python3
"""Wardens' Accord parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/wardens_accord_parity.txt from tools/minigames/wardens_accord.py, playing
demo_action to the end for a fixed set of seeds x difficulties:

  game s=<seed> d=<difficulty> rounds=<n> target=<t> pouch=<n,...> offer=<hue,hue,hue> spirits=<nameIdx:hue=n+hue=n:value;...>
  move t=<turn> kind=<take|summon> i=<i> gained=<g> score=<s> rounds=<n> pouch=<n,...> offer=<...> spirits=<...> over=<0|1> won=<0|1>
  end  score=<s> won=<0|1> summoned=<nameIdx,...>

DaedalusWardensAccordCore.h seeds its own CPython-compatible stream from "wardens_accord:<seed>:<difficulty>".
Run `python tools/minigames/wardens_accord_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wardens_accord as wa  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "wardens_accord_parity.txt")
NAME_IDX = {n: i for i, n in enumerate(wa.NAMES)}


def spirits_str(g):
    return ";".join("%d:%s:%d" % (NAME_IDX[s["name"]], "+".join("%s=%d" % (h, n) for h, n in s["cost"].items()), s["value"])
                    for s in g.spirits)


def state(g):
    return "pouch=%s offer=%s spirits=%s" % (",".join(str(g.pouch[h]) for h in g.hues), ",".join(g.offer), spirits_str(g))


def play(seed, difficulty):
    g = wa.Game(seed, difficulty)
    lines = ["game s=%d d=%s rounds=%d target=%d %s" % (seed, difficulty, g.rounds, g.cfg["target"], state(g))]
    turn = 0
    while not g.over:
        kind, i = g.demo_action()
        gained = g.step((kind, i))
        turn += 1
        lines.append("move t=%d kind=%s i=%d gained=%d score=%d rounds=%d %s over=%d won=%d"
                     % (turn, kind, i, gained, g.score, g.rounds, state(g), int(g.over), int(g.won)))
    lines.append("end  score=%d won=%d summoned=%s" % (g.score, int(g.won), ",".join(str(NAME_IDX[n]) for n in g.summoned)))
    return lines


def generate():
    out = ["# wardens_accord_parity.txt: generated by tools/minigames/wardens_accord_parity.py from wardens_accord.py "
           "(Python rules are the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
