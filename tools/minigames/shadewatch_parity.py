#!/usr/bin/env python3
"""Shadewatch Vigil parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/shadewatch_parity.txt from tools/minigames/shadewatch.py for a fixed set of
seeds x difficulties, playing demo_action to the end:

  game s=<seed> d=<difficulty> hearts=<h> light=<l> lanes=<p,p|p|...>
  move t=<turn> act=<flare:i|kindle|nova> score=<s> hearts=<h> light=<l> burned=<b> over=<0|1> won=<0|1> lanes=<...> res=<text>
  end  score=<s> won=<0|1>

No RNG events are recorded: DaedalusShadewatchCore.h seeds its own CPython-compatible stream from
"shadewatch:<seed>:<difficulty>", so every spawn is part of the parity check.
Run `python tools/minigames/shadewatch_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import shadewatch as sw  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "shadewatch_parity.txt")


def lanes_str(g):
    return "|".join(",".join(str(p) for p in lane) for lane in g.lanes)


def act_str(a):
    return "flare:%d" % a[1] if a[0] == "flare" else a[0]


def play(seed, difficulty):
    g = sw.Game(seed, difficulty)
    lines = ["game s=%d d=%s hearts=%d light=%d lanes=%s" % (seed, difficulty, g.hearts, g.light, lanes_str(g))]
    turn = 0
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        turn += 1
        lines.append("move t=%d act=%s score=%d hearts=%d light=%d burned=%d over=%d won=%d lanes=%s res=%s"
                     % (turn, act_str(a), g.score, g.hearts, g.light, g.burned, int(g.over), int(g.won), lanes_str(g), res))
    lines.append("end  score=%d won=%d" % (g.score, int(g.won)))
    return lines


def generate():
    out = ["# shadewatch_parity.txt: generated by tools/minigames/shadewatch_parity.py from shadewatch.py (Python rules are "
           "the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
