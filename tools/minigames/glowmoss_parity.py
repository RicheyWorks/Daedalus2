#!/usr/bin/env python3
"""Glowmoss Delve parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/glowmoss_parity.txt from tools/minigames/glowmoss.py for a fixed set of
seeds x difficulties, playing demo_action to the end:

  game s=<seed> d=<difficulty> gems=<row/row..> dark=<row/row..> moss=<row/row..> unstable=<row/row..> best=<b> target=<t> plan=<..> row=<r> col=<c> light=<l> crystals=<n> score=<s>
  move t=<turn> act=<dig:c|climb> row=.. col=.. light=.. crystals=.. score=.. path=<..> over=<0|1> won=<0|1> res=<text>
  end  score=<s> won=<0|1> perfect=<0|1>

No RNG events are recorded: DaedalusGlowmossCore.h seeds its own CPython-compatible stream from
"glowmoss:<seed>:<difficulty>", so every ledge's crystals, darkness, glowmoss and footing, the exact best delve (target
and plan) and every demo dig are part of the parity check. All rules math is integer.
Run `python tools/minigames/glowmoss_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import glowmoss as gm  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "glowmoss_parity.txt")


def ints(xs):
    return ",".join(str(x) for x in xs)


def act_str(a):
    return "climb" if a[0] == "climb" else "dig:%d" % a[1]


def grid(rows):
    return "/".join("".join(str(int(x)) for x in row) for row in rows)


def state_str(g):
    return "row=%d col=%d light=%d crystals=%d score=%d path=%s" % (g.row, g.col, g.light, g.crystals, g.score, ints(g.path))


def play(seed, difficulty):
    g = gm.Game(seed, difficulty)
    lines = ["game s=%d d=%s gems=%s dark=%s moss=%s unstable=%s best=%d target=%d plan=%s %s" % (
        seed, difficulty, grid(g.gems), grid(g.dark), grid(g.moss), grid(g.unstable), g.best, g.target, ints(g.plan),
        state_str(g))]
    turn = 0
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        turn += 1
        lines.append("move t=%d act=%s %s over=%d won=%d res=%s" % (turn, act_str(a), state_str(g), int(g.over), int(g.won), res))
    lines.append("end  score=%d won=%d perfect=%d" % (g.score, int(g.won), int(g.perfect)))
    return lines


def generate():
    out = ["# glowmoss_parity.txt: generated by tools/minigames/glowmoss_parity.py from glowmoss.py (Python rules "
           "are the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
