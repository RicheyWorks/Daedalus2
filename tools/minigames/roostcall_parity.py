#!/usr/bin/env python3
"""Roostcall parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/roostcall_parity.txt from tools/minigames/roostcall.py for a fixed set of
seeds x difficulties, playing demo_action to the end:

  game s=<seed> d=<difficulty> size=<n> turns=<t> whistler=<r,c> birds=<r,c;...>
  move t=<turn> act=<n|e|s|w|wait> whistler=<r,c> birds=<r,c;...|-> settled=<k> turns=<t> score=<s> over=<0|1> won=<0|1> res=<text>
  end  score=<s> won=<0|1> settled=<k> turns=<t>

Edge-case vectors follow the seeded yards: a hand-set yard (no seed) and one scripted move each, so both sides prove
the flee rule's corners (sidestep, boxed in, cornered slide, perch, dusk) and the demo pick on states the seeds may
never produce:

  vector <name> size=<n> whistler=<r,c> turns=<t> settled=<k> total=<n> birds=<r,c;...>
  step act=<move> demo=<move> whistler=<r,c> birds=<...> settled=<k> turns=<t> score=<s> over=<0|1> won=<0|1> res=<text>

DaedalusRoostcallCore.h seeds its own CPython-compatible stream from "roostcall:<seed>:<difficulty>", so the
generated yard itself is the parity check, and the demo herding (flee rule, push-spot ranking, BFS in n/e/s/w
order) must match step for step. Run with --check to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import roostcall as rc  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "roostcall_parity.txt")


def cells(v):
    return ";".join("%d,%d" % (r, c) for r, c in v) or "-"


def play(seed, difficulty):
    g = rc.Game(seed, difficulty)
    lines = ["game s=%d d=%s size=%d turns=%d whistler=%d,%d birds=%s"
             % (seed, difficulty, g.size(), g.turns, g.whistler[0], g.whistler[1], cells(g.birds))]
    turn = 0
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        turn += 1
        lines.append("move t=%d act=%s whistler=%d,%d birds=%s settled=%d turns=%d score=%d over=%d won=%d res=%s"
                     % (turn, a, g.whistler[0], g.whistler[1], cells(g.birds), g.settled, g.turns, g.score,
                        int(g.over), int(g.won), res))
    lines.append("end  score=%d won=%d settled=%d turns=%d" % (g.score, int(g.won), g.settled, g.turns))
    return lines


VECTORS = (
    # name, size, whistler, turns, settled, total, birds, scripted move
    ("flee_south", 6, (1, 1), 10, 0, 1, [(2, 1)], "wait"),
    ("cornered_slides_down_the_edge", 6, (0, 4), 10, 0, 1, [(0, 5)], "wait"),
    ("diagonal_does_not_move_a_corner_bird", 6, (1, 4), 10, 0, 1, [(0, 5)], "wait"),
    ("back_taken_sidesteps_east", 6, (1, 1), 10, 0, 2, [(2, 1), (3, 1)], "wait"),
    ("boxed_in_stays", 6, (1, 1), 10, 0, 4, [(2, 1), (3, 1), (2, 2), (2, 0)], "wait"),
    ("tie_north_before_west", 6, (2, 2), 10, 0, 1, [(1, 1)], "wait"),
    ("perch_wins_with_bonus", 6, (2, 4), 5, 0, 1, [(3, 4)], "wait"),
    ("dusk_falls", 6, (0, 0), 1, 1, 2, [(5, 0)], "wait"),
    ("earlier_bird_moves_first", 6, (2, 2), 10, 0, 2, [(2, 3), (2, 4)], "wait"),
    ("walk_into_scare_range", 7, (0, 0), 10, 0, 1, [(3, 3)], "e"),
)


def vector(name, size, whistler, turns, settled, total, birds, move):
    g = rc.Game(1, "easy")
    g.cfg = dict(g.cfg, size=size, birds=total, turns=turns)
    g.whistler, g.birds, g.turns, g.settled = list(whistler), [list(b) for b in birds], turns, settled
    lines = ["vector %s size=%d whistler=%d,%d turns=%d settled=%d total=%d birds=%s"
             % (name, size, whistler[0], whistler[1], turns, settled, total, cells(g.birds))]
    demo = g.demo_action()
    res = g.step(move)
    lines.append("step act=%s demo=%s whistler=%d,%d birds=%s settled=%d turns=%d score=%d over=%d won=%d res=%s"
                 % (move, demo, g.whistler[0], g.whistler[1], cells(g.birds), g.settled, g.turns, g.score, int(g.over),
                    int(g.won), res))
    return lines


def generate():
    out = ["# roostcall_parity.txt: generated by tools/minigames/roostcall_parity.py from roostcall.py (Python rules are "
           "the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    for v in VECTORS:
        out += vector(*v)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
