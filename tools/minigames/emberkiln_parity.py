#!/usr/bin/env python3
"""Emberkiln parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/emberkiln_parity.txt from tools/minigames/emberkiln.py for a fixed set of
seeds x difficulties, playing demo_action to the end:

  game s=<seed> d=<difficulty> size=<n> coals=<k> floor=<row digits;...>     (0 = stone, 2..4 = firing target)
  move t=<turn> act=<r,c> heat=<row digits;...> floor=<...> coals=<k> glazed=<g> cracked=<x> score=<s> over=<0|1> won=<0|1> res=<text>
  end  score=<s> won=<0|1> glazed=<g> cracked=<x> coals=<k>

In `floor`, a glazed tile is written as 9 and a cracked tile as 8, so a row reads as one digit per cell.

Edge-case vectors follow the seeded floors: a hand-set floor (no seed) and one scripted coal each, so both sides prove
the rule corners (stone and glazed tiles passing heat, a crack, a spoiled finish, spent coals, the stoker's tie-break):

  vector <name> size=<n> coals=<k> glazed=<g> cracked=<x> floor=<...> heat=<...>
  step act=<r,c> demo=<r,c> heat=<...> floor=<...> coals=<k> glazed=<g> cracked=<x> score=<s> over=<0|1> won=<0|1> res=<text>

DaedalusEmberkilnCore.h seeds its own CPython-compatible stream from "emberkiln:<seed>:<difficulty>", so the
generated floor itself is the parity check, and the stoker (no-crack, most-glazes, most-raised, row, column)
must match coal for coal. Run with --check to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import emberkiln as ek  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "emberkiln_parity.txt")
FLOOR_DIGIT = {ek.STONE: "0", ek.GLAZED: "9", ek.CRACKED: "8"}


def floor_text(g):
    return ";".join("".join(FLOOR_DIGIT.get(t, str(t)) for t in row) for row in g.target)


def heat_text(g):
    return ";".join("".join(str(h) for h in row) for row in g.heat)


def play(seed, difficulty):
    g = ek.Game(seed, difficulty)
    lines = ["game s=%d d=%s size=%d coals=%d floor=%s" % (seed, difficulty, g.size(), g.coals, floor_text(g))]
    turn = 0
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        turn += 1
        lines.append("move t=%d act=%s heat=%s floor=%s coals=%d glazed=%d cracked=%d score=%d over=%d won=%d res=%s"
                     % (turn, a, heat_text(g), floor_text(g), g.coals, g.glazed, g.cracked, g.score, int(g.over),
                        int(g.won), res))
    lines.append("end  score=%d won=%d glazed=%d cracked=%d coals=%d" % (g.score, int(g.won), g.glazed, g.cracked, g.coals))
    return lines


VECTORS = (
    # name, floor rows (0 stone, 2-4 target, 9 glazed, 8 cracked), heat rows, coals, scripted coal
    ("stone_passes_heat", ["020", "232", "020"], ["000", "000", "000"], 10, "0,0"),
    ("glazed_tile_passes_heat", ["929", "232", "020"], ["202", "121", "000"], 10, "0,1"),
    ("exact_target_glazes_four", ["222", "232", "222"], ["010", "121", "010"], 10, "1,1"),
    ("overshoot_cracks", ["333", "333", "333"], ["000", "020", "000"], 10, "1,1"),
    ("spoiled_finish", ["30", "09"], ["20", "00"], 5, "0,0"),
    ("last_coal_spent", ["44", "44"], ["00", "00"], 1, "0,0"),
    ("shining_finish_with_bonus", ["20", "00"], ["00", "00"], 3, "0,0"),
    ("stoker_prefers_glazes_over_warmth", ["222", "040", "222"], ["101", "000", "101"], 10, "1,1"),
    ("stoker_avoids_the_crack", ["22", "22"], ["11", "10"], 10, "0,0"),
    ("stoker_ties_by_row_then_column", ["33", "33"], ["00", "00"], 10, "1,1"),
)
DIGIT_TARGET = {"0": ek.STONE, "9": ek.GLAZED, "8": ek.CRACKED}


def vector(name, rows, heat, coals, move):
    g = ek.Game(1, "easy")
    s = len(rows)
    g.cfg = dict(g.cfg, size=s, stone=sum(ch == "0" for row in rows for ch in row), coals=coals)
    g.target = [[DIGIT_TARGET.get(ch, int(ch)) for ch in row] for row in rows]
    g.heat = [[int(ch) for ch in row] for row in heat]
    g.coals = coals
    g.glazed = sum(ch == "9" for row in rows for ch in row)
    g.cracked = sum(ch == "8" for row in rows for ch in row)
    lines = ["vector %s size=%d coals=%d glazed=%d cracked=%d floor=%s heat=%s"
             % (name, s, coals, g.glazed, g.cracked, floor_text(g), heat_text(g))]
    demo = g.demo_action()
    res = g.step(move)
    lines.append("step act=%s demo=%s heat=%s floor=%s coals=%d glazed=%d cracked=%d score=%d over=%d won=%d res=%s"
                 % (move, demo, heat_text(g), floor_text(g), g.coals, g.glazed, g.cracked, g.score, int(g.over), int(g.won), res))
    return lines


def generate():
    out = ["# emberkiln_parity.txt: generated by tools/minigames/emberkiln_parity.py from emberkiln.py (Python rules are "
           "the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    for v in VECTORS:
        out += vector(*v)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
