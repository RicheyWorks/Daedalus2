#!/usr/bin/env python3
"""Lumenpath Refraction parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/lumenpath_parity.txt from tools/minigames/lumenpath.py for a fixed set of
seeds x difficulties, playing demo_action to the end:

  game s=<seed> d=<difficulty> size=<n> src=<row> moves=<m> lit=<lit> grid=<row|row|...> crystals=<r,c;...> solution=<r,c,m;...>
  move t=<turn> r=<r> c=<c> gained=<g> score=<s> lit=<lit> moves=<m> over=<0|1> won=<0|1> grid=<row|row|...>
  end  score=<s> won=<0|1>

Unlike the Shardring fixture no RNG events are recorded: DaedalusLumenpathCore.h seeds its own CPython-compatible
stream from "lumenpath:<seed>:<difficulty>", so the generated lattice itself is the parity check.
Run `python tools/minigames/lumenpath_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lumenpath as lp  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "lumenpath_parity.txt")


def grid_str(g):
    return "|".join(g.grid)


def play(seed, difficulty):
    g = lp.Game(seed, difficulty)
    lines = ["game s=%d d=%s size=%d src=%d moves=%d lit=%d grid=%s crystals=%s solution=%s"
             % (seed, difficulty, len(g.grid), g.source_row, g.moves, g.lit, grid_str(g),
                ";".join("%d,%d" % (r, c) for r, c in g.crystals),
                ";".join("%d,%d,%s" % (r, c, m) for r, c, m in g.solution))]
    turn = 0
    while not g.over:
        r, c = g.demo_action()
        gained = g.step((r, c))
        turn += 1
        lines.append("move t=%d r=%d c=%d gained=%d score=%d lit=%d moves=%d over=%d won=%d grid=%s"
                     % (turn, r, c, gained, g.score, g.lit, g.moves, int(g.over), int(g.won), grid_str(g)))
    lines.append("end  score=%d won=%d" % (g.score, int(g.won)))
    return lines


def generate():
    out = ["# lumenpath_parity.txt: generated by tools/minigames/lumenpath_parity.py from lumenpath.py (Python rules are "
           "the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
