#!/usr/bin/env python3
"""Seed each realm's arcade cabinet placement list from the minigame catalog.

Input:  docs/minigames/catalog.json          (generated by minigame_catalog.py)
        data/minigames/realm-arcades.json    (which realms get which cabinets, and how)
Output: data/minigames/realm-cabinets.json   (data only; realm builders spawn from it)

  python tools/minigames/realm_cabinets.py           # regenerate
  python tools/minigames/realm_cabinets.py --check   # CI: fail on bad spec or stale output

Placements are local offsets (metres, Unreal axes: X forward, Y right, Z up) from
the realm's named anchor marker, which the realm builder resolves in its own map.
A realm may set `options: {game: n}`; n is validated against the catalog's
option_count and the host applies it with SetGameOption(n) after StartGame.
Each cabinet carries a stable StartGame seed (crc32 of "realm:game"), so a cabinet
replays the same run wherever it is rebuilt. Stdlib only; no Unreal calls.

Every realm row in docs/REALMS.md (except "PROPOSE ONE") must have a spec entry under
its derived id (see realm_id_from_name). Those ids are proposals, not confirmed by
Richey, so they are marked `id_status: unconfirmed` in the output. The output is
schema-checked before it is written or compared.
"""
import fnmatch
import json
import math
import pathlib
import re
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
CATALOG = ROOT / "docs/minigames/catalog.json"
SPEC = ROOT / "data/minigames/realm-arcades.json"
OUT = ROOT / "data/minigames/realm-cabinets.json"
REALMS_MD = ROOT / "docs/REALMS.md"
LAYOUTS = ("row", "grid", "arc")
PY_HOST = "PythonMinigame"  # data-only host tag; no Unreal actor yet


class SpecError(ValueError):
    pass


def realm_id_from_name(name):
    """'The Orrery Reach' -> 'orrery_reach'; text after ':' or '(' is dropped."""
    base = re.split(r"[:(]", name, 1)[0].strip()
    base = re.sub(r"^the\s+", "", base, flags=re.I)
    slug = re.sub(r"[^a-z0-9]+", "_", base.lower()).strip("_")
    if not slug:
        raise SpecError(f"cannot derive a realm id from '{name}'")
    return slug


def parse_realms_md(text):
    """Realm table rows -> [{'id', 'name', 'status'}] in file order. Skips PROPOSE ONE rows."""
    out = []
    for line in text.splitlines():
        m = re.match(r"\|\s*\*\*([^*]+)\*\*([^|]*)\|[^|]*\|\s*([^|]*?)\s*\|", line)
        if not m:
            continue
        status = m.group(3).strip()
        if status.upper().startswith("PROPOSE"):
            continue
        out.append({"id": realm_id_from_name(m.group(1)), "name": m.group(1).strip(), "status": status})
    ids = [r["id"] for r in out]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SpecError(f"docs/REALMS.md realm names collide on derived ids: {', '.join(dupes)}")
    return out


def validate(data):
    """Schema check for realm-cabinets.json. Raises SpecError on the first problem."""
    if data.get("schema") != "daedalus.minigames.realm_cabinets/v1":
        raise SpecError("schema must be daedalus.minigames.realm_cabinets/v1")
    if not isinstance(data.get("realms"), list) or not data["realms"]:
        raise SpecError("realms must be a non-empty list")
    seen = set()
    for r in data["realms"]:
        rid = r.get("realm")
        if not isinstance(rid, str) or not re.fullmatch(r"[a-z0-9_]+", rid) or rid in seen:
            raise SpecError(f"bad or duplicate realm id {rid!r}")
        seen.add(rid)
        if not isinstance(r.get("anchor"), str) or not r["anchor"] or r.get("layout") not in LAYOUTS:
            raise SpecError(f"realm '{rid}' needs a string anchor and a known layout")
        if r.get("id_status", "confirmed") not in ("confirmed", "unconfirmed"):
            raise SpecError(f"realm '{rid}' id_status must be confirmed or unconfirmed")
        cabs = r.get("cabinets")
        if not isinstance(cabs, list) or not cabs:
            raise SpecError(f"realm '{rid}' has no cabinets")
        games, spots = set(), set()
        for c in cabs:
            g = c.get("game")
            if not isinstance(g, str) or g in games:
                raise SpecError(f"realm '{rid}' has a bad or repeated game {g!r}")
            games.add(g)
            off = c.get("offset_m")
            if not (isinstance(off, list) and len(off) == 3 and all(isinstance(v, (int, float)) for v in off)):
                raise SpecError(f"realm '{rid}' cabinet '{g}' offset_m must be 3 numbers")
            if tuple(off) in spots:
                raise SpecError(f"realm '{rid}' cabinet '{g}' overlaps another cabinet")
            spots.add(tuple(off))
            if not isinstance(c.get("yaw_deg"), (int, float)) or not 0 <= c["yaw_deg"] < 360:
                raise SpecError(f"realm '{rid}' cabinet '{g}' yaw_deg must be 0..360")
            if c.get("seed") != stable_seed(rid, g):
                raise SpecError(f"realm '{rid}' cabinet '{g}' seed is not crc32('{rid}:{g}')")
            if c.get("host") not in ("ADaedalusDesktopArcade", "ADaedalusJavaArcade", PY_HOST):
                raise SpecError(f"realm '{rid}' cabinet '{g}' has unknown host {c.get('host')!r}")
    return data


def stable_seed(realm, game):
    return zlib.crc32(f"{realm}:{game}".encode("utf-8")) & 0x7FFFFFFF


def offsets(layout, count, spacing, columns=4, radius=None):
    """Local (x, y, yaw) offsets for `count` cabinets. Cabinets face the anchor."""
    if count <= 0:
        return []
    if layout == "row":
        mid = (count - 1) / 2.0
        return [(0.0, round((i - mid) * spacing, 3), 180.0) for i in range(count)]
    if layout == "grid":
        cols = max(1, min(columns, count))
        rows = math.ceil(count / cols)
        out = []
        for i in range(count):
            r, c = divmod(i, cols)
            in_row = min(cols, count - r * cols)
            out.append((round(r * spacing, 3), round((c - (in_row - 1) / 2.0) * spacing, 3), 180.0))
        assert len(out) == count and rows >= 1
        return out
    if layout == "arc":
        rad = radius if radius else max(spacing, spacing * count / math.pi)
        span = min(math.pi, spacing * (count - 1) / rad) if count > 1 else 0.0
        out = []
        for i in range(count):
            a = -span / 2 + (span * i / (count - 1) if count > 1 else 0.0)
            x, y = rad * math.cos(a), rad * math.sin(a)
            yaw = (math.degrees(math.atan2(-y, -x)) + 360.0) % 360.0
            out.append((round(x, 3), round(y, 3), round(yaw, 3)))
        return out
    raise SpecError(f"unknown layout '{layout}' (use one of {', '.join(LAYOUTS)})")


def select(ids, include, exclude):
    chosen = [g for g in ids if any(fnmatch.fnmatchcase(g, p) for p in include)]
    return [g for g in chosen if not any(fnmatch.fnmatchcase(g, p) for p in exclude)]


def build(catalog, spec, realms_md=None):
    desktop = {g["id"]: g for g in catalog.get("games", [])}
    java = {j["id"]: j for j in catalog.get("java_cabinets", [])}
    python = {g["id"]: g for g in catalog.get("python_games", [])}
    known = list(desktop) + [i for i in java if i not in desktop]
    defaults = spec.get("defaults", {})
    seen = set()
    realms = []
    for r in spec.get("realms", []):
        rid = r.get("realm")
        if not rid or not isinstance(rid, str):
            raise SpecError("every realm needs a string 'realm' id")
        if rid in seen:
            raise SpecError(f"realm '{rid}' is listed twice")
        seen.add(rid)
        include = r.get("include", defaults.get("include", ["*"]))
        exclude = r.get("exclude", [])
        for p in list(include) + list(exclude):
            if not any(ch in p for ch in "*?[") and p not in desktop and p not in java and p not in python:
                raise SpecError(f"realm '{rid}' names unknown game '{p}'")
        games = select(known, include, exclude)
        # Python games are placed only when named explicitly (never by a glob).
        games += [g for g in python if g in include and g not in exclude and g not in games]
        if not r.get("java", defaults.get("java", True)):
            games = [g for g in games if g not in java]
        if not games:
            raise SpecError(f"realm '{rid}' selects no cabinets")
        layout = r.get("layout", defaults.get("layout", "row"))
        spacing = float(r.get("spacing_m", defaults.get("spacing_m", 2.5)))
        if not (0.5 <= spacing <= 20):
            raise SpecError(f"realm '{rid}' spacing_m must be 0.5..20")
        places = offsets(layout, len(games), spacing, int(r.get("columns", defaults.get("columns", 4))), r.get("radius_m"))
        options = r.get("options", {})
        if not isinstance(options, dict):
            raise SpecError(f"realm '{rid}' options must map game id -> option number")
        for gid, opt in options.items():
            if gid not in games:
                raise SpecError(f"realm '{rid}' sets an option for '{gid}', which it does not place")
            if gid in python:
                raise SpecError(f"realm '{rid}' sets an option for Python game '{gid}'; use its difficulty")
            if gid in java:
                raise SpecError(f"realm '{rid}' sets an option for Java cabinet '{gid}'; Java cabinets have no options")
            count = desktop[gid].get("option_count", 0)
            if not isinstance(opt, int) or isinstance(opt, bool) or not (0 <= opt < max(count, 1)):
                raise SpecError(f"realm '{rid}' option {opt!r} for '{gid}' is out of range (0..{max(count, 1) - 1})")
        cabinets = []
        for gid, (x, y, yaw) in zip(games, places):
            if gid in python:
                p = python[gid]
                seed = stable_seed(rid, gid)
                cabinets.append({"game": gid, "title": p["title"], "host": PY_HOST, "offset_m": [x, y, 0.0],
                                 "yaw_deg": yaw, "seed": seed, "difficulty": p["default_difficulty"],
                                 "module": p["module"], "start": p["start"].replace("seed", str(seed), 1),
                                 "requires": "no native host yet; rules run in the Python module"})
                continue
            entry = java.get(gid) if gid in java else desktop[gid]
            cab = {"game": gid, "title": entry["title"], "host": entry["host"],
                   "offset_m": [x, y, 0.0], "yaw_deg": yaw, "seed": stable_seed(rid, gid)}
            if gid in java:
                cab["game_enum"] = entry["game_enum"]
                cab["requires"] = entry["requires"]
            else:
                cab["option"] = options.get(gid, 0)
                cab["start"] = f'StartGame("{gid}", {cab["seed"]})'
            cabinets.append(cab)
        row = {"realm": rid, "anchor": r.get("anchor", defaults.get("anchor", "arcade_plaza")), "layout": layout}
        if realms_md is not None and rid in {m["id"] for m in realms_md}:
            row["realms_md_name"] = next(m["name"] for m in realms_md if m["id"] == rid)
            row["id_status"] = "unconfirmed"
        row["cabinets"] = cabinets
        realms.append(row)
    if realms_md is not None:
        missing = [m["id"] for m in realms_md if m["id"] not in seen]
        if missing:
            raise SpecError("docs/REALMS.md realms with no cabinet entry in realm-arcades.json: " + ", ".join(missing))
    return validate({"schema": "daedalus.minigames.realm_cabinets/v1",
                     "generated_by": "tools/minigames/realm_cabinets.py",
                     "note": ("Offsets are metres from each realm's anchor marker; native status per catalog.json. "
                              "id_status unconfirmed: realm id derived from docs/REALMS.md, awaiting Richey."),
                     "realms": realms})


def render(data):
    return json.dumps(data, indent=2) + "\n"


def main(argv):
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    try:
        realms_md = parse_realms_md(REALMS_MD.read_text(encoding="utf-8")) if REALMS_MD.exists() else None
        text = render(build(catalog, spec, realms_md))
    except SpecError as e:
        print("FAIL:", e)
        return 1
    if "--check" in argv:
        cur = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if cur != text:
            print("FAIL: data/minigames/realm-cabinets.json is stale; run python tools/minigames/realm_cabinets.py")
            return 1
        print("realm cabinets ok")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {sum(len(r['cabinets']) for r in json.loads(text)['realms'])} cabinets in {len(spec.get('realms', []))} realms")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
