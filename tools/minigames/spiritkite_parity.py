#!/usr/bin/env python3
"""Spiritkite Weave parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/spiritkite_parity.txt from tools/minigames/spiritkite.py for a fixed set of
seeds x difficulties, playing demo_action to the end:

  game s=<seed> d=<difficulty> lanes=<a-b-w,..> values=<..> target=<t> plan=<..> at=<i> wind=<w> score=<s>
  move t=<turn> act=<fly:i|land> at=.. wind=.. score=.. gathered=<..> trail=<..> over=<0|1> won=<0|1> res=<text>
  end  score=<s> won=<0|1>

No RNG events are recorded: DaedalusSpiritkiteCore.h seeds its own CPython-compatible stream from
"spiritkite:<seed>:<difficulty>", so the isle layout, every wind lane, the lantern values, the exact best round
trip (target and plan) and every demo hop are part of the parity check.
Run `python tools/minigames/spiritkite_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import spiritkite as sk  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "spiritkite_parity.txt")


def ints(xs):
    return ",".join(str(x) for x in xs)


def act_str(a):
    return "land" if a[0] == "land" else "fly:%d" % a[1]


def state_str(g):
    return "at=%d wind=%d score=%d gathered=%s trail=%s" % (g.at, g.wind, g.score, ints(g.gathered), ints(g.trail))


def play(seed, difficulty):
    g = sk.Game(seed, difficulty)
    lanes = ",".join("%d-%d-%d" % tuple(lane) for lane in g.lanes)
    lines = ["game s=%d d=%s lanes=%s values=%s target=%d plan=%s %s" % (
        seed, difficulty, lanes, ints(g.values), g.target, ints(g.plan), state_str(g))]
    turn = 0
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        turn += 1
        lines.append("move t=%d act=%s %s over=%d won=%d res=%s" % (turn, act_str(a), state_str(g), int(g.over), int(g.won), res))
    lines.append("end  score=%d won=%d" % (g.score, int(g.won)))
    return lines


def generate():
    out = ["# spiritkite_parity.txt: generated by tools/minigames/spiritkite_parity.py from spiritkite.py (Python rules "
           "are the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
