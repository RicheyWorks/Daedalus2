#!/usr/bin/env python3
"""Facetlock Lattice parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/facetlock_parity.txt from tools/minigames/facetlock.py:

  game s=<seed> d=<difficulty> size=<n> moves=<m> board=<row|row|...> solution=<r|c,i,d;...>
  move t=<turn> kind=<r|c> i=<i> d=<+1|-1> gained=<g> score=<s> moves=<m> over=<0|1> won=<0|1> board=<...> solution=<...>
  end  score=<s> won=<0|1>

Run `python tools/minigames/facetlock_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import facetlock as fl  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "facetlock_parity.txt")


def sol(g):
    return ";".join("%s,%d,%d" % (k, i, d) for k, i, d in g.solution)


def play(seed, difficulty):
    g = fl.Game(seed, difficulty)
    lines = ["game s=%d d=%s size=%d moves=%d board=%s solution=%s" % (seed, difficulty, len(g.board), g.moves, "|".join(g.board), sol(g))]
    turn = 0
    while not g.over:
        kind, i, d = g.demo_action()
        gained = g.step((kind, i, d))
        turn += 1
        lines.append("move t=%d kind=%s i=%d d=%d gained=%d score=%d moves=%d over=%d won=%d board=%s solution=%s"
                     % (turn, kind, i, d, gained, g.score, g.moves, int(g.over), int(g.won), "|".join(g.board), sol(g)))
    lines.append("end  score=%d won=%d" % (g.score, int(g.won)))
    return lines


def generate():
    out = ["# facetlock_parity.txt: generated by tools/minigames/facetlock_parity.py from facetlock.py (Python rules are "
           "the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
