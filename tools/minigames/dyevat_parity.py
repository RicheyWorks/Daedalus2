#!/usr/bin/env python3
"""Dyevat parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/dyevat_parity.txt from tools/minigames/dyevat.py for a fixed set of
seeds x difficulties, playing demo_action to the end:

  game s=<seed> d=<difficulty> vats=<vat;vat;...> pours=<k>              (each vat bottom to top, '-' when empty)
  move t=<turn> act=<a,b> vats=<...> sealed=<0/1 per vat> pours=<k> score=<n> over=<0|1> won=<0|1> res=<text>
  end  score=<n> won=<0|1> sealed=<count> pours=<k>

then hand-set vectors that pin the edge rules (run pours, partial fits, seals, illegal pours, no pour left).
Run with --check in CI so the committed file never drifts from the rules.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dyevat as dv  # noqa: E402

SEEDS = tuple(range(10))
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "dyevat_parity.txt")


def vats_text(g):
    return ";".join("".join(str(x) for x in vat) or "-" for vat in g.vats)


def sealed_text(g):
    return "".join("1" if s else "0" for s in g.sealed)


def play(seed, difficulty):
    g = dv.Game(seed, difficulty)
    lines = ["game s=%d d=%s vats=%s sealed=%s pours=%d" % (seed, difficulty, vats_text(g), sealed_text(g), g.pours)]
    turn = 0
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        turn += 1
        lines.append("move t=%d act=%s vats=%s sealed=%s pours=%d score=%d over=%d won=%d res=%s"
                     % (turn, a, vats_text(g), sealed_text(g), g.pours, g.score, int(g.over), int(g.won), res))
    lines.append("end  score=%d won=%d sealed=%d pours=%d" % (g.score, int(g.won), g.sealed_count(), g.pours))
    return lines


VECTORS = (
    # name, vats (bottom to top, '-' empty), hues, pours, scripted pour ('x' prefix: expected illegal)
    ("run_moves_whole", ["1122", "-", "1"], 2, 10, "0,1"),
    ("partial_fit", ["1222", "122", "1"], 2, 10, "0,1"),
    ("seal_scores", ["1222", "2", "11"], 2, 10, "0,1"),
    ("win_bonus", ["2222", "111", "1"], 2, 6, "2,1"),
    ("last_pour_spent", ["1212", "2121", "-"], 2, 1, "0,2"),
    ("no_pour_left", ["1232", "3121", "212"], 3, 10, "0,2"),
    ("mismatch_illegal", ["12", "21", "-"], 2, 10, "x0,1"),
    ("full_illegal", ["12", "2121", "-"], 2, 10, "x0,1"),
    ("sealed_locked", ["1111", "22", "2"], 2, 10, "x0,2"),
    ("dyer_prefers_seal", ["122", "222", "1", "-"], 2, 10, "0,1"),
    ("dyer_skips_undo", ["12", "2", "1", "-"], 2, 10, "1,0"),
)


def vector(name, rows, hues, pours, move):
    g = dv.Game(1, "easy")
    g.cfg = dict(g.cfg, hues=hues, empty=sum(r == "-" for r in rows), pours=pours)
    g.vats = [[] if r == "-" else [int(ch) for ch in r] for r in rows]
    g.sealed = [g.full_one_hue(v) for v in range(len(g.vats))]
    g.pours, g.score, g.over, g.won = pours, 0, False, False
    g.last = [-1, -1]
    if name == "dyer_skips_undo":
        g.last = [0, 1]
    lines = ["vector %s hues=%d pours=%d last=%d,%d vats=%s sealed=%s"
             % (name, hues, pours, g.last[0], g.last[1], vats_text(g), sealed_text(g))]
    demo = g.demo_action()
    illegal = move.startswith("x")
    act = move.lstrip("x")
    try:
        res = g.step(act)
    except ValueError as e:
        assert illegal, name
        res = "illegal: %s" % e
    else:
        assert not illegal, name
    lines.append("step act=%s demo=%s vats=%s sealed=%s pours=%d score=%d over=%d won=%d res=%s"
                 % (act, demo, vats_text(g), sealed_text(g), g.pours, g.score, int(g.over), int(g.won), res))
    return lines


def generate():
    out = ["# dyevat_parity.txt: generated by tools/minigames/dyevat_parity.py from dyevat.py (Python rules are "
           "the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    for v in VECTORS:
        out += vector(*v)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
