#!/usr/bin/env python3
"""PyRandom parity fixture: CPython random.Random(str) is the authority, DaedalusPyRandomCore.h must match bit for bit.

Writes engines/unreal/core-test/pyrandom_parity.txt. One block per seed string, each line a method call made in
order on the same generator, so the stream position carries from line to line exactly as it does in the games:

  seed <string>
  u32 <getrandbits(32)>
  below n=<n> <_randbelow(n)>
  randrange n=<n> <randrange(n)>
  double <repr(random())>
  sample n=<n> k=<k> <indices...>
  shuffle n=<n> <permutation of range(n)...>
  drawn <32-bit words consumed so far>

`drawn` lets the native side prove its Drawn()/Discard() save fast-forward: after Discard(drawn) on a fresh
generator the next u32 must equal the next line. Run with --check to verify the committed file is current.
"""
import argparse
import os
import random
import sys

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "pyrandom_parity.txt")
SEEDS = ("shardring:0:normal", "shardfall:42:hard", "prismvault:65535:easy", "lumenpath:2026:normal", "", "a",
         "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef", "unicode:éλ☃")


class Counting(random.Random):
    """random.Random that counts 32-bit words, the way PyRandom.Drawn() does."""
    def __init__(self, seed):
        self.words = 0
        super().__init__(seed)

    def getrandbits(self, k):
        self.words += (k + 31) // 32
        return super().getrandbits(k)

    def random(self):
        self.words += 2
        return super().random()


def block(seed):
    rng = Counting(seed)
    lines = ["seed %s" % seed]
    for _ in range(3):
        lines.append("u32 %d" % rng.getrandbits(32))
    for n in (1, 2, 3, 7, 10, 16, 100, 1000, 2 ** 31 - 1):
        lines.append("below n=%d %d" % (n, rng._randbelow(n)))
    for n in (5, 12, 1 << 20):
        lines.append("randrange n=%d %d" % (n, rng.randrange(n)))
    for _ in range(3):
        lines.append("double %r" % rng.random())
    for n, k in ((10, 3), (12, 12), (30, 6), (100, 8), (26, 7)):
        picks = rng.sample(range(n), k)
        lines.append("sample n=%d k=%d %s" % (n, k, ",".join(str(p) for p in picks)))
    for n in (1, 2, 5, 15, 52):
        order = list(range(n))
        rng.shuffle(order)
        lines.append("shuffle n=%d %s" % (n, ",".join(str(v) for v in order)))
    lines.append("drawn %d" % rng.words)
    lines.append("u32 %d" % rng.getrandbits(32))
    return lines


def generate():
    out = ["# pyrandom_parity.txt: generated by tools/minigames/pyrandom_parity.py from CPython random (the authority). "
           "Do not hand-edit."]
    for s in SEEDS:
        out += block(s)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
