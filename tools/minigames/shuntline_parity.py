#!/usr/bin/env python3
"""Shuntline parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/shuntline_parity.txt from tools/minigames/shuntline.py for a fixed set of
seeds x difficulties, playing demo_action (the yardmaster) to the end:

  game s=<seed> d=<difficulty> cars=<n> sidings=<k> length=<l> moves=<m> train=<t,t,...>
  move t=<turn> act=<out|s<n>|p<n>> index=<i> sidings=<a,b|-;...> outbound=<...|-> moves=<m> score=<s> over=<0|1> won=<0|1> res=<text>
  end  score=<s> won=<0|1> out=<n> moves=<m>

DaedalusShuntlineCore.h seeds its own CPython-compatible stream from "shuntline:<seed>:<difficulty>" and repeats the
redraw-until-solvable loop, so the train itself is the parity check, and the yardmaster's exact search (actions in
the rules' order, the same prunes and node budget) must match move for move. Run with --check to verify the committed
file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import shuntline as sl  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "shuntline_parity.txt")


def ints(v):
    return ",".join(str(x) for x in v) or "-"


def sidings_text(g):
    return ";".join(ints(s) for s in g.sidings)


def play(seed, difficulty):
    g = sl.Game(seed, difficulty)
    cfg = g.cfg
    lines = ["game s=%d d=%s cars=%d sidings=%d length=%d moves=%d train=%s"
             % (seed, difficulty, cfg["cars"], cfg["sidings"], cfg["length"], cfg["moves"], ints(g.train))]
    turn = 0
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        turn += 1
        lines.append("move t=%d act=%s index=%d sidings=%s outbound=%s moves=%d score=%d over=%d won=%d res=%s"
                     % (turn, a, g.index, sidings_text(g), ints(g.outbound), g.moves, g.score, int(g.over), int(g.won), res))
    lines.append("end  score=%d won=%d out=%d moves=%d" % (g.score, int(g.won), len(g.outbound), g.moves))
    return lines


def generate():
    out = ["# shuntline_parity.txt: generated by tools/minigames/shuntline_parity.py from shuntline.py (Python rules are "
           "the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
