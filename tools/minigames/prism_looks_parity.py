#!/usr/bin/env python3
"""Prism Looks parity fixture (Python rules are the authority; the native core must match).

Writes engines/unreal/core-test/prism_looks_parity.txt from tools/minigames/prism_looks.py:

  skin g=<game> id=<skin> name=<name, spaces as +> base=<RRGGBB> accent=<RRGGBB> glow=<RRGGBB> seal=<k> gap=<luma gap>
  unlock g=<game> seal=<k> skins=<id,id,..>
  pick g=<game> seal=<k> want=<skin id or -> show=<skin id>
  reject g=<game> seal=<k>

DaedalusPrismLooksCore.h must reproduce every output field from the inputs (game, seal, wanted skin) alone.
Run `python tools/minigames/prism_looks_parity.py --check` to verify.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import prism_looks as pl  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "prism_looks_parity.txt")
REJECTS = (("nogame", 0), ("glowmoss", 7), ("glowmoss", -1), ("", 3), ("Facetlock", 0))


def build():
    out = ["# prism_looks_parity.txt: generated by tools/minigames/prism_looks_parity.py from prism_looks.py "
           "(Python rules are the authority). Do not hand-edit."]
    games = sorted(pl.SKINS)
    for g in games:
        for s in pl.SKINS[g]:
            out.append(f"skin g={g} id={s[0]} name={s[1].replace(' ', '+')} base={s[2]:06X} accent={s[3]:06X} "
                       f"glow={s[4]:06X} seal={s[5]} gap={pl.luma_gap(s)}")
    for g in games:
        for k in range(len(pl.SEAL_NAMES)):
            out.append(f"unlock g={g} seal={k} skins={','.join(pl.unlocked(g, k))}")
    for g in games:
        ids = [s[0] for s in pl.SKINS[g]] + ["-", "shardring_heart" if g != "shardring" else "glowmoss_heart"]
        for k in (0, 2, 3, 5, 6):
            for w in ids:
                out.append(f"pick g={g} seal={k} want={w} show={pl.pick(g, k, w)}")
    for g, k in REJECTS:
        try:
            pl.unlocked(g, k)
        except ValueError:
            out.append(f"reject g={g or '-'} seal={k}")
        else:
            raise SystemExit(f"expected reject for {g!r} {k}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        with open(OUT, encoding="utf-8", newline="") as f:
            if f.read() != text:
                print("prism_looks_parity.txt is stale; run tools/minigames/prism_looks_parity.py")
                return 1
        print("prism_looks_parity.txt is current")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
