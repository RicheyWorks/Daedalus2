#!/usr/bin/env python3
"""Prismvault Weigh parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/prismvault_parity.txt from tools/minigames/prismvault.py:

  game s=<seed> d=<difficulty> shards=<n> hollow=<h> weighings=<w> candidates=<...>
  move t=<turn> kind=<weigh|name> left=<a,b|-> right=<c,d|-> shard=<i|-1> res=<<|>|=|-> gained=<g> score=<s> weighings=<w> candidates=<...> over=<0|1> won=<0|1>
  end  score=<s> won=<0|1>

Run `python tools/minigames/prismvault_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import prismvault as pv  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "prismvault_parity.txt")


def lst(v):
    return ",".join(map(str, v)) if v else "-"


def play(seed, difficulty):
    g = pv.Game(seed, difficulty)
    lines = ["game s=%d d=%s shards=%d hollow=%d weighings=%d candidates=%s" % (seed, difficulty, g.cfg["shards"], g.hollow, g.weighings, lst(g.candidates))]
    turn = 0
    while not g.over:
        a = g.demo_action()
        r = g.step(a)
        turn += 1
        if a[0] == "weigh":
            lines.append("move t=%d kind=weigh left=%s right=%s shard=-1 res=%s gained=0 score=%d weighings=%d candidates=%s over=%d won=%d"
                         % (turn, lst(a[1]), lst(a[2]), r, g.score, g.weighings, lst(g.candidates), int(g.over), int(g.won)))
        else:
            lines.append("move t=%d kind=name left=- right=- shard=%d res=- gained=%d score=%d weighings=%d candidates=%s over=%d won=%d"
                         % (turn, a[1], r, g.score, g.weighings, lst(g.candidates), int(g.over), int(g.won)))
    lines.append("end  score=%d won=%d" % (g.score, int(g.won)))
    return lines


def generate():
    out = ["# prismvault_parity.txt: generated by tools/minigames/prismvault_parity.py from prismvault.py (Python rules are "
           "the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
