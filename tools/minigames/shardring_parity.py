#!/usr/bin/env python3
"""Shardring Resonance parity fixture generator (Python rules are the authority; native replays them).

Writes engines/unreal/core-test/shardring_parity.txt from tools/minigames/prism_shard.py by playing greedy_move for
a fixed set of seeds x difficulties and recording every RNG decision as data, so a native core needs no PRNG port:

  game s=<seed> d=<difficulty> facets=<n> hues=<k> shards=<n>
  rng  draw <hue> | spirit <facet>         (every random.choice the rules made, in order)
  move t=<turn> facet=<f> gained=<g> score=<s> chain=<c> pouch=<p> cur=<hue> next=<hue> spirits=<n> ring=<.ETVGU...> over=<0|1> won=<0|1>
  end  score=<s> won=<0|1> spirits=<a,b,...>

The native core (DaedalusShardringCore.h) is handed the `rng` lines as an oracle and must produce identical `move`
and `end` lines. Run `python tools/minigames/shardring_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import prism_shard as ps  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "shardring_parity.txt")
MARK = {h: h[0].upper() for h in ps.HUES}


class Recorder:
    """Wraps random.Random: logs each choice() as a draw (hue) or a spirit pick (facet)."""

    def __init__(self, inner, hues):
        self.inner, self.hues, self.log = inner, hues, []

    def choice(self, seq):
        r = self.inner.choice(seq)
        self.log.append(("draw", r) if seq is self.hues else ("spirit", r))
        return r

    def __getattr__(self, name):
        return getattr(self.inner, name)


def ring_str(ring):
    return "".join(MARK[h] if h else "." for h in ring)


def play(seed, difficulty):
    g = ps.ShardringGame(seed, difficulty)
    # restart with the recorder in place so the first two draws are captured too
    g.rng = Recorder(ps.random.Random(f"{ps.GAME_ID}:{g.seed}:{g.difficulty}"), g.hues)
    cfg = ps.DIFFICULTY[difficulty]
    g.ring, g.pouch, g.score, g.chain = [None] * cfg["facets"], cfg["shards"], 0, 0
    g.resonance, g.spirits, g.over, g.won = {h: 0 for h in g.hues}, [], False, False
    g.current, g.next = g._draw(), g._draw()
    lines = ["game s=%d d=%s facets=%d hues=%d shards=%d" % (seed, difficulty, cfg["facets"], cfg["hues"], cfg["shards"])]
    moves = []
    turn = 0
    while not g.over:
        facet = ps.greedy_move(g)
        gained = g.place(facet)
        turn += 1
        moves.append("move t=%d facet=%d gained=%d score=%d chain=%d pouch=%d cur=%s next=%s spirits=%d ring=%s over=%d won=%d"
                     % (turn, facet, gained, g.score, g.chain, g.pouch, g.current, g.next, len(g.spirits), ring_str(g.ring),
                        int(g.over), int(g.won)))
    for kind, value in g.rng.log:
        lines.append("rng  %s %s" % (kind, value))
    lines += moves
    lines.append("end  score=%d won=%d spirits=%s" % (g.score, int(g.won), ",".join(g.spirits)))
    return lines


def generate():
    out = ["# shardring_parity.txt: generated by tools/minigames/shardring_parity.py from prism_shard.py (Python rules are "
           "the authority). %d seeds x %s, greedy_move. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
