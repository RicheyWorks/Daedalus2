#!/usr/bin/env python3
"""Prismcairn Duel parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/prismcairn_parity.txt from tools/minigames/prismcairn.py:

  game s=<seed> d=<difficulty> round=<r> cairns=<h,h,...>
  move t=<turn> i=<i> take=<t> out=<you|warden|warden_last> wi=<cairn|-1> wt=<take|-1> round=<r> wins=<w> losses=<l> score=<s> cairns=<...> over=<0|1> won=<0|1>
  end  score=<s> won=<0|1> rounds=<r>

Run `python tools/minigames/prismcairn_parity.py --check` to verify the committed file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import prismcairn as pcn  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "prismcairn_parity.txt")


def play(seed, difficulty):
    g = pcn.Game(seed, difficulty)
    lines = ["game s=%d d=%s round=%d cairns=%s" % (seed, difficulty, g.round, ",".join(map(str, g.cairns)))]
    turn = 0
    while not g.over:
        i, t = g.demo_action()
        msg = g.step((i, t))
        row = g.log[-1]
        if row[3] == "round":
            out, wi, wt = "you", -1, -1
        else:
            wi, wt = row[4], row[5]
            out = "warden_last" if msg.endswith("lifts the last shard") else "warden"
        turn += 1
        lines.append("move t=%d i=%d take=%d out=%s wi=%d wt=%d round=%d wins=%d losses=%d score=%d cairns=%s over=%d won=%d"
                     % (turn, i, t, out, wi, wt, g.round, g.wins, g.losses, g.score, ",".join(map(str, g.cairns)), int(g.over), int(g.won)))
    lines.append("end  score=%d won=%d rounds=%d" % (g.score, int(g.won), g.round))
    return lines


def generate():
    out = ["# prismcairn_parity.txt: generated by tools/minigames/prismcairn_parity.py from prismcairn.py (Python rules are "
           "the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
