#!/usr/bin/env python3
"""Stonecourse parity fixture (Python rules are the authority; the native core must match from seed alone).

Writes engines/unreal/core-test/stonecourse_parity.txt from tools/minigames/stonecourse.py for a fixed set of
seeds x difficulties, playing demo_action (the mason) to the end:

  game s=<seed> d=<difficulty> width=<w> courses=<h> skips=<k> stones=<w,w,...>
  move t=<turn> act=<col|skip> index=<i> wall=<course rows bottom first, ;-joined> locked=<n> skips=<k> score=<s> over=<0|1> won=<0|1> res=<text>
  end  score=<s> won=<0|1> locked=<n> index=<i>

Edge-case vectors follow the seeded walls: a hand-set wall and supply (no seed) and one scripted action each, so both
sides prove the rule corners (landing on support, a lock, a skip, the stuck ending, the supply ending, the finish)
and the mason's pick on states the seeds may never produce:

  vector <name> width=<w> courses=<h> skips=<k> stones=<...> index=<i> wall=<rows>
  step act=<col|skip> demo=<col|skip> index=<i> wall=<rows> locked=<n> skips=<k> score=<s> over=<0|1> won=<0|1> res=<text>

DaedalusStonecourseCore.h seeds its own CPython-compatible stream from "stonecourse:<seed>:<difficulty>" and repeats
the redraw-until-solvable loop, so the supply itself is the parity check, and the mason's bounded search (columns
left to right, then skip; SEARCH_NODES budget) must match turn for turn. Run with --check to verify the committed
file is current.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import stonecourse as sc  # noqa: E402

SEEDS = (0, 1, 2, 3, 7, 11, 42, 1337, 2026, 65535)
DIFFS = ("easy", "normal", "hard")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "engines", "unreal", "core-test",
                   "stonecourse_parity.txt")


def ints(v):
    return ",".join(str(x) for x in v) or "-"


def wall_text(g):
    return ";".join("".join(str(x) for x in row) for row in g.wall)


def play(seed, difficulty):
    g = sc.Game(seed, difficulty)
    cfg = g.cfg
    lines = ["game s=%d d=%s width=%d courses=%d skips=%d stones=%s" % (seed, difficulty, cfg["width"], cfg["courses"], cfg["skips"], ints(g.stones))]
    turn = 0
    while not g.over:
        a = g.demo_action()
        res = g.step(a)
        turn += 1
        lines.append("move t=%d act=%s index=%d wall=%s locked=%d skips=%d score=%d over=%d won=%d res=%s"
                     % (turn, a, g.index, wall_text(g), g.locked, g.skips_left, g.score, int(g.over), int(g.won), res))
    lines.append("end  score=%d won=%d locked=%d index=%d" % (g.score, int(g.won), g.locked, g.index))
    return lines


VECTORS = (
    # name, width, rows (footing first), stones, index, skips, action
    ("lands_on_the_footing", 5, ["00000", "00000"], [2, 2, 1], 0, 1, "0"),
    ("lands_on_full_support", 5, ["11000", "00000"], [2, 3], 0, 1, "0"),
    ("course_locks", 5, ["11110", "00000"], [1, 3, 2], 0, 1, "4"),
    ("skip_to_the_rubble", 5, ["11011", "00000"], [3, 1, 1], 0, 2, "skip"),
    ("stuck_with_no_skips", 5, ["11011", "00000"], [3, 3], 0, 1, "skip"),
    ("supply_runs_out", 3, ["100"], [1, 1], 1, 1, "1"),
    ("the_wall_stands", 3, ["110", "111"], [1, 2, 2], 0, 2, "2"),
    ("mason_keeps_the_gap_fillable", 5, ["00000", "00000"], [3, 1, 1, 2, 3], 0, 1, "0"),
    ("mason_builds_up_before_filling_the_gap", 4, ["1110", "0000"], [3, 1, 3, 1], 0, 1, "skip"),
)


def vector(name, width, rows, stones, index, skips, action):
    g = sc.Game(1, "easy")
    g.cfg = dict(g.cfg, width=width, courses=len(rows), supply=len(stones), skips=skips)
    g.stones, g.index, g.skips_left = list(stones), index, skips
    g.wall = [[int(ch) for ch in row] for row in rows]
    g.locked = sum(1 for row in g.wall if all(row))
    lines = ["vector %s width=%d courses=%d skips=%d stones=%s index=%d wall=%s"
             % (name, width, len(rows), skips, ints(stones), index, wall_text(g))]
    demo = g.demo_action()
    res = g.step(action)
    lines.append("step act=%s demo=%s index=%d wall=%s locked=%d skips=%d score=%d over=%d won=%d res=%s"
                 % (action, demo, g.index, wall_text(g), g.locked, g.skips_left, g.score, int(g.over), int(g.won), res))
    return lines


def generate():
    out = ["# stonecourse_parity.txt: generated by tools/minigames/stonecourse_parity.py from stonecourse.py (Python rules "
           "are the authority). %d seeds x %s, demo_action. Do not hand-edit." % (len(SEEDS), "/".join(DIFFS))]
    for d in DIFFS:
        for s in SEEDS:
            out += play(s, d)
    for v in VECTORS:
        out += vector(*v)
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args(argv)
    text = generate()
    if a.check:
        with open(a.out, encoding="utf-8") as fh:
            same = fh.read() == text
        print("parity file %s" % ("current" if same else "STALE"))
        return 0 if same else 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (os.path.normpath(a.out), text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
