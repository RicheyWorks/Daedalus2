"""Parity fixture for the Java day book (com.daedalus.world.colony, contest gap G15).

Runs the real Python cores (colony_ledger.Ledger.day_book/requests + island_chemistry) over a spread of realms,
deeds, days, hours, seasons and seral stages, plus raw CPython random draws, and writes a plain TSV that
DayBookParityTest / PyRandomTest replay in Java (no JSON library needed in daedalus-core).

    python tools/economy/daybook_parity.py          # rewrite the fixture
    python tools/economy/daybook_parity.py --check  # exit 1 if the fixture is stale (run by test_daybook_parity.py)

Line kinds (tab-separated, lists joined with ','; empty list = '-'):
  RND   seed  op  args  -> result          raw random.Random(seed) draws
  CASE  realm deed fish crater orchard makeable need catalog roles quests(giver:id:steps|...)
  DAY   day hour seral season  finds  new  bonus  requests(npc;wants;pays;quest|...)  store_after  charm
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import colony_ledger as C  # noqa: E402

OUT = os.path.join(ROOT, "daedalus-core", "src", "test", "resources", "com", "daedalus", "world", "colony", "daybook-parity.tsv")
CASES = [("WORLD-ZERO", 240), ("WORLD-ZERO", 7), ("WORLD-ZERO", 1234), ("PORTAL", 7), ("PORTAL", 42),
         ("LABYRINTH", 5), ("PRISMHEART", 99), ("PARCELS", 310), ("WORLD-ZERO", 43)]
SEASONS = ("spring", "summer", "autumn", "winter")
HOURS = (8, 13, 18, 21, 6, 2, 10, 17)


def j(xs):
    xs = list(xs)
    return ",".join(str(x) for x in xs) if xs else "-"


def num(x):
    return repr(float(x))


def rnd_lines():
    out = []
    for seed in (0, 1, 42, 240 * 100003 + 3, 7 * 7 + 13, 2 ** 40 + 5, -17):
        r = random.Random(seed)
        out.append(["RND", seed, "random", "-", repr(r.random())])
        r = random.Random(seed)
        out.append(["RND", seed, "getrandbits", "1,7,31,32,33,53", j(r.getrandbits(k) for k in (1, 7, 31, 32, 33, 53))])
        r = random.Random(seed)
        out.append(["RND", seed, "randbelow", "3,10,100,1000", j(r.randrange(n) for n in (3, 10, 100, 1000))])
        r = random.Random(seed)
        pool = list(range(30))
        out.append(["RND", seed, "sample", "30,3", j(r.sample(pool, 3))])       # set branch (n > 21)
        r = random.Random(seed)
        out.append(["RND", seed, "sample", "12,5", j(r.sample(pool[:12], 5))])   # pool branch
        r = random.Random(seed)
        out.append(["RND", seed, "sample", "100,8", j(r.sample(list(range(100)), 8))])  # k > 5 setsize
    return out


def case_lines(realm, deed):
    L = C.Ledger(realm, seed=1)
    L.claim("richey", deed)
    p = L.plots[deed]
    ch = p.chem
    pop = C.population(L.realm)
    makeable = set(ch["soil"]["crops"]) | set(ch["flora"]["herbs"]) | set(ch["ores_here"]) | {"crystal", "plank"}
    makeable |= {i["fruit"] for i in ch["flora"]["orchard"].values()} | {y.split("@")[0] for y in ch["fauna"]["livestock"].values()}
    quests = "|".join("%s:%s:%d" % (q.get("giver_type", ""), q["id"], len(q.get("steps", []))) for q in pop["quests"]) or "-"
    out = [["CASE", L.realm, deed, j(ch["water"]["fish"]), int(bool(ch["geology"]["starmetal_crater"])),
            j(i["fruit"] for i in ch["flora"]["orchard"].values()), j(sorted(makeable)), ch["economy"]["need"],
            j(C.catalog(L.realm)), j(pop["types"]), quests]]
    for day in range(1, 9):
        hour = HOURS[(day + deed) % len(HOURS)]
        eco = {"seral": (day + deed) % 4, "biodiversity": 1.0, "season": SEASONS[(day // 2 + deed) % 4]}
        d = L.day_book(deed, day, hour, eco)
        reqs = "|".join("%s;%s;%s;%s" % (r["npc"], j(r["wants"]), r["pays"], r["quest"] or "-") for r in d["requests"]) or "-"
        store = j("%s=%s" % (k, num(v)) for k, v in sorted(p.store.items()))
        out.append(["DAY", day, hour, eco["seral"], eco["season"], j(d["finds"]), j(d["new_in_collection"]), num(d["bonus"]),
                    reqs, store, repr(round(p.charm, 9))])
    return out


def render():
    lines = ["# generated by tools/economy/daybook_parity.py from colony_ledger.py + island_chemistry.py; do not edit"]
    for row in rnd_lines():
        lines.append("\t".join(str(x) for x in row))
    for realm, deed in CASES:
        for row in case_lines(realm, deed):
            lines.append("\t".join(str(x) for x in row))
    return "\n".join(lines) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                same = f.read() == text
        except OSError:
            same = False
        print("fixture %s" % ("up to date" if same else "STALE: run python tools/economy/daybook_parity.py"))
        return 0 if same else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d lines)" % (OUT, text.count("\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
