def render(text, col, shadow=None, spacing=1):
    text = text.upper()
    w = len(text) * (5 + spacing)
    h = 7 + (1 if shadow is not None else 0)
    a = np.zeros((h, w + (1 if shadow is not None else 0), 4), np.float32)
    for i, ch in enumerate(text):
        g = G.get(ch, G["?"])
        x0 = i * (5 + spacing)
        for y, row in enumerate(g):
            for x, c in enumerate(row):
                if c == "#":
                    if shadow is not None:
                        a[y + 1, x0 + x + 1, :3] = shadow
                        a[y + 1, x0 + x + 1, 3] = 1
    for i, ch in enumerate(text):
        g = G.get(ch, G["?"])
        x0 = i * (5 + spacing)
        for y, row in enumerate(g):
            for x, c in enumerate(row):
                if c == "#":
                    a[y, x0 + x, :3] = col
                    a[y, x0 + x, 3] = 1
    return a


def atlas(col=(1, 1, 1)):
    chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .,:!?/-'>+_"
    cols = 16
    rows = -(-len(chars) // cols)
    a = np.zeros((rows * 8, cols * 6, 4), np.float32)
    for i, ch in enumerate(chars):
        r, c = divmod(i, cols)
        g = render(ch, col, spacing=0)
        a[r * 8:r * 8 + 7, c * 6:c * 6 + 5] = g[:7, :5]
    return a, chars


assert all(len(g) == 7 and all(len(r) == 5 for r in g) for g in G.values())
