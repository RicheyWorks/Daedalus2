"""G158 Toll Bridge Tokens (DiskSaver Island, quest q_toll_bridge_tokens).

Save writes cross the toll bridge to the archive. The arrivals are the G126
Breakwater Queue harbour waves (calm trickles, swells, a storm season),
generated by the landed `breakwater_queue.arrivals` on its shipped data,
read-only. The archive's write buffer holds at most `buffer` writes in any
`window` consecutive ticks; more than that in some window and the bridge
sways (overload). A write turned back at the toll is rejected (the client
backs off, G134). The toll keeper picks the gate:
  open          no toll: every write crosses, the storm sways the bridge
  fixed_window  at most `limit` writes per aligned block of `window` ticks;
                a burst at the end of one block plus one at the start of the
                next lets 2 x limit cross inside one window
  token_bucket  tokens drip in at limit/window per tick into a bucket of
                `burst` tokens; a write needs one token. Any span of t ticks
                admits at most burst + (t-1)*limit/window writes.
Win: the bridge never sways and at least `min_admitted_permille` of the
writes cross. A huge bucket lets storm bursts sway the bridge; a tiny bucket
turns back too many honest writes. Deterministic and offline: integer
milli-tokens.

Reusable pieces:
  validate(cfg) -> Config
  TokenBucket(rate_milli, burst) / FixedWindow(limit, window)
  admitted_series(config, gate, burst=None) -> per-tick admitted counts
  max_in_window(series, w) / envelope(burst, rate, t) / envelope_ok(series, burst, rate, spans)
  simulate(config, gate=None, burst=None) -> Result
  solve_burst(config): largest bucket safe for every arrival pattern
  islands_from_shoals(shoals_cfg)  tie-in: islands + keys_per_island = G86
  npc_say / receipt
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

QUEST_ID = "q_toll_bridge_tokens"
VERSION = 1
ID_CHARS = set("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_")
GATES = ("open", "fixed_window", "token_bucket")
WON, FAILED = "won", "failed"
FAIL_SWAY, FAIL_REJECT = "bridge_swayed", "too_many_rejected"
NPC_KEYS = ("start", "toll", "sway", "win", "fail")
TOP_KEYS = {"v", "quest", "lore", "bridge", "islands", "seed", "npc"}
B_KEYS = {"keys_per_island", "window", "buffer", "limit", "burst", "gate", "min_admitted_permille", "harbour_data"}


class TollError(ValueError):
    pass


@dataclass(frozen=True)
class Config:
    keys_per_island: int
    window: int
    buffer: int
    limit: int
    burst: int
    gate: str
    min_admitted_permille: int
    harbour_data: str
    islands: Tuple[str, ...]
    seed: int
    npc_name: str
    lines: Dict[str, str]


def _int(v, name, lo, hi):
    if isinstance(v, bool) or not isinstance(v, int) or v < lo or v > hi:
        raise TollError(f"{name} must be an integer in [{lo}, {hi}]")
    return v


def validate(cfg) -> Config:
    if not isinstance(cfg, dict):
        raise TollError("config must be an object")
    if set(cfg) - TOP_KEYS:
        raise TollError(f"unknown keys: {sorted(set(cfg) - TOP_KEYS)}")
    if cfg.get("v") != VERSION:
        raise TollError("v must be 1")
    if cfg.get("quest", QUEST_ID) != QUEST_ID:
        raise TollError(f"quest must be {QUEST_ID}")
    h = cfg.get("bridge")
    if not isinstance(h, dict) or set(h) != B_KEYS:
        raise TollError(f"bridge must have exactly {sorted(B_KEYS)}")
    kpi = _int(h["keys_per_island"], "keys_per_island", 1, 100_000)
    w = _int(h["window"], "window", 1, 100_000)
    buf = _int(h["buffer"], "buffer", 1, 10_000_000)
    lim = _int(h["limit"], "limit", 1, buf)
    bur = _int(h["burst"], "burst", 1, 10_000_000)
    if h["gate"] not in GATES:
        raise TollError(f"gate must be one of {GATES}")
    mp = _int(h["min_admitted_permille"], "min_admitted_permille", 0, 1000)
    hd = h["harbour_data"]
    if not isinstance(hd, str) or not hd.endswith(".json") or "/" in hd or "\\" in hd:
        raise TollError("harbour_data must be a json file name in data/islands/disk-saver")
    isl = cfg.get("islands")
    if not isinstance(isl, list) or not isl:
        raise TollError("islands must be a non-empty list")
    seen = []
    for it in isl:
        iid = it.get("id") if isinstance(it, dict) else None
        if not isinstance(iid, str) or not iid or set(iid) - ID_CHARS or iid in seen:
            raise TollError(f"bad or duplicate island id: {iid!r}")
        seen.append(iid)
    seed = _int(cfg.get("seed", 1), "seed", 0, 2 ** 32 - 1)
    npc = cfg.get("npc")
    if not isinstance(npc, dict) or not isinstance(npc.get("name"), str):
        raise TollError("npc must have a name")
    lines = npc.get("lines")
    if not isinstance(lines, dict) or set(lines) != set(NPC_KEYS):
        raise TollError(f"npc.lines must have exactly {list(NPC_KEYS)}")
    if not all(isinstance(v, str) and v for v in lines.values()):
        raise TollError("npc lines must be non-empty strings")
    return Config(kpi, w, buf, lim, bur, h["gate"], mp, hd, tuple(seen), seed, npc["name"], dict(lines))


class TokenBucket:
    """Integer milli-tokens: `rate_milli` added per tick, capped at burst * 1000; a write costs 1000."""

    def __init__(self, rate_milli: int, burst: int):
        if rate_milli < 0 or burst < 1:
            raise TollError("bad bucket")
        self.rate, self.cap = rate_milli, burst * 1000
        self.level = self.cap

    def tick(self):
        self.level = min(self.cap, self.level + self.rate)

    def take(self) -> bool:
        if self.level >= 1000:
            self.level -= 1000
            return True
        return False


class FixedWindow:
    def __init__(self, limit: int, window: int):
        self.limit, self.window, self.used, self.block = limit, window, 0, 0

    def tick(self, now: int):
        if now // self.window != self.block:
            self.block, self.used = now // self.window, 0

    def take(self) -> bool:
        if self.used < self.limit:
            self.used += 1
            return True
        return False


def harbour_waves(c: Config, root: str = ROOT) -> List[int]:
    """Arrivals per tick from the landed G126 Breakwater Queue (read-only)."""
    import breakwater_queue as bq
    with open(os.path.join(root, "data", "islands", "disk-saver", c.harbour_data), encoding="utf-8") as fh:
        hc = bq.validate(json.load(fh))
    return [len(w) for w in bq.arrivals(hc)]


def admitted_series(c: Config, gate: str, burst: Optional[int] = None, waves: Optional[List[int]] = None) -> List[int]:
    waves = harbour_waves(c) if waves is None else waves
    out = []
    if gate == "open":
        return list(waves)
    if gate == "fixed_window":
        fw = FixedWindow(c.limit, c.window)
        for t, n in enumerate(waves):
            fw.tick(t)
            out.append(sum(1 for _ in range(n) if fw.take()))
        return out
    if gate == "token_bucket":
        tb = TokenBucket(rate_milli(c), c.burst if burst is None else burst)
        for n in waves:
            tb.tick()
            out.append(sum(1 for _ in range(n) if tb.take()))
        return out
    raise TollError(f"unknown gate {gate!r}")


def max_in_window(series: List[int], w: int) -> int:
    best = run = 0
    for i, x in enumerate(series):
        run += x
        if i >= w:
            run -= series[i - w]
        best = max(best, run)
    return best


def rate_milli(c: Config) -> int:
    return c.limit * 1000 // c.window


def envelope(burst: int, rate_m: int, t: int) -> int:
    """Most writes a token bucket can admit in any span of t ticks: the bucket is at most full
    after the first tick's drip, then t-1 more drips: floor((1000*burst + (t-1)*rate) / 1000).
    Tight when the bucket holds at least one tick's drip (burst*1000 >= rate)."""
    return (1000 * burst + (t - 1) * rate_m) // 1000


def envelope_ok(series: List[int], burst: int, rate_m: int, spans) -> bool:
    return all(max_in_window(series, t) <= envelope(burst, rate_m, t) for t in spans)


def solve_burst(c: Config) -> int:
    """Largest bucket that can never sway the bridge for any arrivals: envelope(window) <= buffer."""
    b = c.buffer - ((c.window - 1) * rate_milli(c)) // 1000
    while b > 1 and envelope(b, rate_milli(c), c.window) > c.buffer:
        b -= 1
    return b


@dataclass
class Result:
    status: str
    reason: Optional[str]
    arrived: int
    admitted: int
    rejected: int
    admitted_permille: int
    worst_window: int


def simulate(c: Config, gate: Optional[str] = None, burst: Optional[int] = None,
             waves: Optional[List[int]] = None) -> Result:
    g = c.gate if gate is None else gate
    waves = harbour_waves(c) if waves is None else waves
    s = admitted_series(c, g, burst, waves)
    arrived, admitted = sum(waves), sum(s)
    worst = max_in_window(s, c.window)
    pm = admitted * 1000 // arrived if arrived else 1000
    if worst > c.buffer:
        status, reason = FAILED, FAIL_SWAY
    elif pm < c.min_admitted_permille:
        status, reason = FAILED, FAIL_REJECT
    else:
        status, reason = WON, None
    return Result(status, reason, arrived, admitted, arrived - admitted, pm, worst)


def islands_from_shoals(shoals_cfg) -> Tuple[List[dict], int]:
    """G86 tie-in: islands and keys_per_island from Compaction Shoals, read-only."""
    return ([{"id": it["id"]} for it in shoals_cfg["islands"]],
            shoals_cfg["shoals"]["keys_per_island"])


def npc_say(c: Config, key: str) -> str:
    return f"{c.npc_name}: {c.lines[key]}"


def receipt(c: Config, r: Result, gate: str, burst: int) -> dict:
    return {"quest": QUEST_ID, "status": r.status, "reason": r.reason, "gate": gate, "burst": burst,
            "arrived": r.arrived, "admitted": r.admitted, "rejected": r.rejected,
            "admitted_permille": r.admitted_permille, "worst_window": r.worst_window, "buffer": c.buffer}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("config")
    ap.add_argument("--gate", choices=GATES, default=None)
    ap.add_argument("--burst", type=int, default=None, help="token bucket size override")
    a = ap.parse_args(argv)
    with open(a.config, encoding="utf-8") as fh:
        c = validate(json.load(fh))
    g = c.gate if a.gate is None else a.gate
    bur = c.burst if a.burst is None else a.burst
    r = simulate(c, g, bur)
    print(npc_say(c, "start"))
    print(json.dumps(receipt(c, r, g, bur), sort_keys=True))
    print(npc_say(c, "win" if r.status == WON else "fail"))
    return 0 if r.status == WON else 1


if __name__ == "__main__":
    sys.exit(main())
