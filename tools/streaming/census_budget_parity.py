"""Golden outputs for the C++17 port of the G206 cost model (census_budget.py).

Writes engines/unreal/core-test/census_budget_parity.txt from the Python tool; the
header-only DaedalusCensusBudgetCore.h replays it line for line in
engines/unreal/core-test/census_budget_core_test.cpp.

Cases: the real world_census fixtures (alpha + beta + bindings), seeded synthetic censuses
(the seeds are drawn here in Python only, so the C++ side needs no RNG), and edge counts at
and just over the 40000 KiB RAM / 32768 KiB disk budgets and their 900 permille warn lines,
each under the shipped config plus a tight and a lopsided budget.

  python tools/streaming/census_budget_parity.py            # print
  python tools/streaming/census_budget_parity.py --check    # exit 1 if the checked-in file is stale
  python tools/streaming/census_budget_parity.py --write    # rewrite the checked-in file
"""
import hashlib
import json
import os
import random
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import census_budget as cb  # noqa: E402

ROOT = cb.ROOT
OUT = os.path.join(ROOT, "engines", "unreal", "core-test", "census_budget_parity.txt")
FIX = os.path.join(ROOT, "tools", "world_census", "fixtures")
SEEDS = (1, 7, 42, 206)
# 0/1 | disk warn 264/265 | disk budget 298/299 | ram warn 815/816 | ram budget 984/985 | huge
EDGE_COUNTS = (0, 1, 264, 265, 298, 299, 815, 816, 984, 985, 5000, 4166000)


def real_census():
    with tempfile.TemporaryDirectory() as t:
        out = os.path.join(t, "c")
        subprocess.run([sys.executable, "-B", "-m", "tools.world_census", os.path.join(FIX, "alpha.json"),
                        os.path.join(FIX, "beta.json"), "--snapshot-date", "2026-10-26", "--bindings",
                        os.path.join(FIX, "bindings.json"), "--output-dir", out], cwd=ROOT, check=True,
                       capture_output=True)
        with open(os.path.join(out, "census.json"), encoding="utf-8") as f:
            return json.load(f)


def census(worlds):
    return {"format": "daedalus-world-census", "version": 1, "count_semantics": "asset-definitions",
            "snapshot_date": "2026-10-29",
            "worlds": [{"id": w, "islands": [{"slot": s, "asset_definitions": n} for s, n in isl]}
                       for w, isl in worlds]}


def seeded(seed):
    rng = random.Random(int(hashlib.sha256(f"g206-cpp|{seed}".encode()).hexdigest(), 16))
    worlds = []
    for w in range(rng.randint(1, 4)):
        slots = rng.sample(range(64), rng.randint(0, 7))
        worlds.append((f"w{seed}_{w}", [(s, rng.choice((rng.randint(0, 120), rng.randint(200, 1100))))
                                        for s in slots]))
    return census(worlds)


def budgets():
    with open(cb.DEFAULT_CONFIG, encoding="utf-8") as f:
        default = json.load(f)
    tight = {"budget": {"ram_budget_kib": 16384, "disk_budget_kib": 4096, "warn_permille": 1000}}
    lopsided = {"budget": {"ram_budget_kib": cb.MAX_KIB, "disk_budget_kib": 1, "warn_permille": 1}}
    return [("default", default), ("tight", tight), ("lopsided", lopsided)]


def cases():
    yield "real_fixtures", real_census()
    for s in SEEDS:
        yield f"seed_{s}", seeded(s)
    yield "edges", census([("edge", list(enumerate(EDGE_COUNTS)))])
    yield "spill_ram", census([("ram_spill", [(0, 984), (1, 0), (2, 0)])])
    yield "spill_disk", census([("disk_spill", [(0, 298), (1, 1)])])
    yield "empty_world", census([("bare", [])])


def lines():
    out = ["# census_budget parity v1: generated by tools/streaming/census_budget_parity.py; do not edit",
           f"M {cb.BASE_RAM_KIB} {cb.PER_ASSET_RAM_KIB} {cb.BASE_DISK_KIB} {cb.PER_ASSET_DISK_KIB}"]
    for bname, cfg in budgets():
        rb, db, warn = cb.load_budget(cfg)
        for cname, doc in cases():
            r = cb.plan(doc, cfg)
            out.append(f"C {cname} {bname} {rb} {db} {warn}")
            for w in r["worlds"]:
                out.append(f"W {w['id']} {len(w['islands'])} {w['total_ram_kib']} {w['total_disk_kib']} "
                           f"{int(w['fits_all_resident'])} {w['max_resident']}")
                for i in w["islands"]:
                    out.append(f"I {i['slot']} {i['asset_definitions']} {i['ram_kib']} {i['disk_kib']} "
                               f"{','.join(i['flags']) or '-'} {i['beacon']}")
            s = r["summary"]
            out.append(f"S {s['worlds']} {s['islands']} {s['green']} {s['amber']} {s['red']} "
                       f"{s['worlds_spilling']}")
    return "\n".join(out) + "\n"


def main(argv):
    text = lines()
    if "--write" in argv:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        return 0
    if "--check" in argv:
        with open(OUT, encoding="utf-8") as f:
            ok = f.read() == text
        print("census_budget parity " + ("up to date" if ok else "STALE: rerun with --write"))
        return 0 if ok else 1
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
