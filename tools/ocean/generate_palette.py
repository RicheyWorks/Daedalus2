"""Generate native Ocean palette metadata from the existing Java canonical tables."""
import argparse
import hashlib
from pathlib import Path
import re

REPO=Path(__file__).resolve().parents[2]
COLORS=REPO/'daedalus-core/src/main/java/com/daedalus/world/export/BlockColors.java'
TYPES=REPO/'daedalus-core/src/main/java/com/daedalus/world/BlockType.java'
OUTPUT=REPO/'engines/unreal/DaedalusLink/Source/DaedalusLink/Private/DaedalusOceanPalette.inl'

def generate():
    colors=COLORS.read_text(encoding='utf-8');types=TYPES.read_text(encoding='utf-8')
    names=re.findall(r'^\s*([A-Z][A-Z0-9_]*)(?:,|;)',types,re.M)
    rgb=dict(re.findall(r'RGB\.put\(BlockType\.([A-Z0-9_]+), (0x[0-9a-f]+)\);',colors))
    # Refuse silent rule drift: these expressions are the current Java semantics.
    compact=lambda text:re.sub(r'\s+','',text)
    translucent='return type == BlockType.GLASS || type == BlockType.WATER || type == BlockType.PORTAL || type.name().startsWith("RAINBOW_");'
    see='return this == AIR || this == GLASS || this == WATER || this == CLOUD || this == PORTAL || name().startsWith("RAINBOW_");'
    if len(names)<40 or compact(translucent) not in compact(colors) or compact(see) not in compact(types):
        raise ValueError('Canonical Java palette rules changed; update generator explicitly')
    digest=hashlib.sha256((colors+types).encode()).hexdigest()
    rows=['// Generated by tools/ocean/generate_palette.py; do not edit.',f'// Java source SHA256: {digest}',
          'namespace DaedalusOceanPalette {','struct Entry { const char* Name; uint32 Rgb; bool Translucent; bool SeeThrough; };',
          'static constexpr Entry Entries[] = {']
    for name in names:
        blend=name in ['GLASS','WATER','PORTAL'] or name.startswith('RAINBOW_')
        through=blend or name in ['AIR','CLOUD']
        rows.append(f'    {{"{name}", {rgb.get(name,"0x888888")}, {str(blend).lower()}, {str(through).lower()}}},')
    rows+=['};','}']
    return '\n'.join(rows)+'\n'

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    expected=generate()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8')!=expected:raise SystemExit('Native Ocean palette drift')
        print('OCEAN_PALETTE_PARITY_PASS')
    else:
        OUTPUT.write_text(expected,encoding='utf-8',newline='\n')
        print('Generated native palette from Java canon')
