#!/usr/bin/env python3
"""Teeth for CampaignService — the ladder's selection rules, its bounds, and its honesty.

Different from the two ticker harnesses on purpose. `CampaignServiceTest` is the most
self-aware test in the repo: it sweeps many seeds rather than one *because* a single-seed version
of itself once passed while the ladder walked backwards on 15 of 40 seeds, and it carries a
second parameterised test at ten stages solely because it measured that the default config cannot
pin the clear-the-previous rule (60/60 monotone with the rule, 60/60 without). A suite that has
already deleted a rule to check whether its own assertions notice is not going to fall for the
obvious mutations.

So these aim at the parts of the class that were *measured during development and then written
down in prose* — the numbers in the javadoc that no assertion mentions:

  * **the conservative target range.** `targetFor` returns `2.5 + t * 8.5`, and the javadoc
    records that raising it to the nominally more accurate `2.8 … 13` collapsed monotonicity from
    60/60 seeds to 34/60, because every stage then picked the hardest maze available and left the
    next stage nothing to beat. That is a load-bearing constant justified by an experiment;
    mutation asks whether anything would notice it drifting back.
  * **the three-size candidate pool.** Selecting from a single size gave 25/40. The pool width is
    what fixed it, and it is one `Math.max(5, nominal + (sizeVariant - 1) * 2)` away from gone.
  * **the hardest-candidate fallback.** Taking `hardest` unconditionally is exactly the failure
    the conservative targets exist to avoid, reached by a different route.
  * **`gradeOf`'s start/goal placement**, whose comment says the grade must describe "precisely
    the maze that gets served". Skip it and the ladder is still deterministic, still ordered, and
    every score in the response now describes a maze nobody plays.
  * **the campaign-plan bound**, the house rule this class states and no test checks.
  * **`allStagesStillCached`**, the eviction path — a stage whose maze was dropped must be
    replanned, not handed out as a 404-shaped id.

**The finding worth more than the survivors.** Two mutations survived outright (the plan bound and
the eviction path, both now pinned). But four others were reported *caught* by a single test —
`DeterminismGoldenTest`, which compares endpoint output against recorded digests. Re-running those
four with the golden test excluded from the class list is the measurement that matters, and three
of them then survived: the target range could revert to the configuration the javadoc records as
34/60 monotone, the candidate pool could collapse to the single size recorded as 25/40, and the
hazard ramp could dump both hazards at the half-way mark, and every campaign-specific assertion
still passed. Only the bytes noticed.

A golden digest is a change detector, not a property. It fires on every mutation here because
every mutation changes the output — and it is regenerated by whoever deliberately retunes a
constant, which is exactly when a collapse in monotonicity would ride along unnoticed. Counting
its failures as catches inflates this harness's score while pinning nothing. So: the seed sweep in
`theMeasuredDifficultyClimbsAcrossStages` went from five seeds to twenty (it now fails on the
target and pool mutations by itself, at a cost of half a second), and the hazard test pins the
whole ramp rung by rung instead of its two ends.

One mutation was retired rather than pinned. Colliding candidate seeds across size variants —
`seedFor(seed, index, c)` instead of `seedFor(seed, index, sizeVariant * candidates + c)` —
survives everything except the digest, and it should: the three size variants share three seeds,
but a seed at a different size is a different maze, so the pool is still nine distinct candidates
graded on their merits. It changes which mazes are considered, not how many or how they are
chosen. That is the third category this folder keeps meeting: not caught, not inert, but breaking
no promise the class makes.

Usage:  python3 mutants/campaignteeth.py
"""
import pathlib, subprocess

import verdict as V

REPO = pathlib.Path(__file__).resolve().parent.parent
CS = REPO / "daedalus-server/src/main/java/com/daedalus/server/service/CampaignService.java"

MUT = [
    (CS, "the campaign-plan map loses its bound",
     "        if (plans.size() >= maxCampaigns) {",
     "        if (false) {"),
    (CS, "an evicted stage is served instead of replanned",
     "            if (gen.find(s.mazeId()) == null) {\n"
     "                return false; // evicted — recompute the plan from the same seeds\n"
     "            }",
     "            if (false) {\n"
     "                return false; // evicted — recompute the plan from the same seeds\n"
     "            }"),
    (CS, "stage() stops rejecting out-of-range indices",
     "        if (index < 0 || index >= c.stages().size()) {",
     "        if (index >= c.stages().size() + 1000) {"),
    (CS, "targets rise to the pool's ceiling (the 34/60 configuration)",
     "        return 2.5 + t * 8.5;",
     "        return 2.8 + t * 10.2;"),
    (CS, "the candidate pool collapses to one size",
     "            int size = Math.max(5, nominal + (sizeVariant - 1) * 2);",
     "            int size = Math.max(5, nominal);"),
    (CS, "the hardest candidate always wins (target ignored)",
     "        Candidate chosen = best != null ? best : hardest;",
     "        Candidate chosen = hardest;"),
    (CS, "the clear-the-previous rule is dropped",
     "                if (candidate.grade.score() > previousScore\n"
     "                        && (best == null",
     "                if ((best == null"),
    (CS, "the previous stage's score is never carried forward",
     "            previousScore = stage.grade().score();",
     "            previousScore = 0.0;"),
    (CS, "grading measures a maze with no start or goal placed",
     "        MazeMetrics.placeStartAndGoalAtExtremes(grid);\n"
     "        return DifficultyGrader.grade(grid);",
     "        return DifficultyGrader.grade(grid);"),
    (CS, "the generator ladder wraps instead of holding at its last rung",
     "        String generatorId = GENERATOR_LADDER[Math.min(index, GENERATOR_LADDER.length - 1)];",
     "        String generatorId = GENERATOR_LADDER[index % GENERATOR_LADDER.length];"),
    (CS, "seed mixing loses its avalanche step",
     "        return mixed ^ Long.rotateLeft(mixed, 31);",
     "        return mixed;"),
    (CS, "hazards all arrive at once, half way up",
     "            if (index >= (int) Math.ceil(stageCount * 0.75)) hazards.add(\"traffic\");",
     "            if (index >= (int) Math.ceil(stageCount * 0.5)) hazards.add(\"traffic\");"),
]

CLASSES = ("CampaignServiceTest", "CampaignEndpointTest", "DeterminismGoldenTest")
TESTS = ",".join(CLASSES)


def run_once():
    p = subprocess.run(["mvn", "-B", "-ntp", "-pl", "daedalus-server", "test",
                        "-Dtest=" + TESTS,
                        "-Dsurefire.failIfNoSpecifiedTests=false",
                        "-Dcheckstyle.skip", "-Dspotbugs.skip", "-Djacoco.skip"],
                       cwd=REPO, capture_output=True, text=True, timeout=1800)
    return V.classify(p.returncode, p.stdout, V.failing_tests(p.stdout, *CLASSES))


V.restore_on_signal()
originals = {p: p.read_text() for p in {m[0] for m in MUT}}
V.snapshot(originals)
survivors = []
try:
    for path, name, old, new in MUT:
        orig = originals[path]
        if orig.count(old) != 1:
            print(f"{name:58s} -> SKIP (anchor x{orig.count(old)})", flush=True)
            survivors.append(name + " [anchor lost]")
            continue
        path.write_text(orig.replace(old, new))
        try:
            v = run_once()
        except subprocess.TimeoutExpired:
            v = "caught: timed out"
        finally:
            path.write_text(orig)
        if not V.is_catch(v):
            survivors.append(name)
        print(f"{name:58s} -> {v}", flush=True)
finally:
    for path, text in originals.items():
        path.write_text(text)
    V.release()
    print("restored")

print(f"\n{len(MUT) - len(survivors)}/{len(MUT)} caught; survivors: {survivors or 'none'}")
